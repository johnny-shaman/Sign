{
	let rows = 0;
	let bad = 0;
	for (const r of seen) {
		for (const v of r.values) {
			const t = r.trees[v.index];
			if (!t || !(t.t === "unit" || kindOf(t) === "L")) continue;
			rows++;
			if (v.value !== UNIT) {
				bad++;
				console.log(`   突き合わせ: 行 ${v.line} の木は ${t.t === "unit" ? "(unit …)" : "L"} なのに値は ${showValue(v.value)}`);
			}
		}
	}
	check(`突き合わせ（${rows} 行）`, rows > 0 && bad === 0);
}

