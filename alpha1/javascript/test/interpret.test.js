// 走らせた結果を全部覚えて、最後に解決器と突き合わせる（3）。
const seen = [];
function run(lines, { std = true, workLimit } = {}) {
	const r = interpret([...(std ? STD : []), ...[].concat(lines)].join("\n"), workLimit ? { workLimit } : {});
	seen.push(r);
	return r;
}
const lastValue = (r) => r.values[r.values.length - 1].value;
// 最後の行の値の綴り。止まったら `止まった(理由@行)`（試験を続けるため）。
const show = (src, opts) => {
	try {
		return showValue(lastValue(run(src, opts)));
	} catch (e) {
		return `止まった(${e.reason || e.name}@${e.line})`;
	}
};

