// **綴りを鍵に、その演算の中身を構造体で持つ。**
//
//     `+` :
//         tier : 14
//         name : `add`
//
// 位置ごとに表を分けてあるのは、多義な綴り（`#` は前置の段1と中置の段4）の鍵を衝突させない
// ためで、`.js` が `OPERATOR_DICT` で定義の配列にしているのと同じ情報である。
//
// ## どの綴りも同じ欄を持たなければならない
//
// パーサはトークン（実行時の値）を鍵にして引く。**鍵が実行時に決まる引き方は、どの綴りも
// 同じ形のときだけ出せる**——実測：
//
//     欄を綴りごとに省く（形が揃わない）   機械 ✗「まだ出せない識別子です（tier）」
//     どの綴りも同じ欄を持つ（揃う）       機械 ○
//     静的な鍵なら                       揃わなくても ○
//
// だから**どの綴りも持つもの**（段・演算の名前）だけをここへ入れる。持つ綴りと持たない綴りが
// 分かれるもの（曖昧でない中置か・どの命令で出るか）は**所属の問い**なので、別の表で持つ
// ——無い側はそもそも記述せず、引けば `__` が返る。それが唯一の偽である。
//
// **値を `__` にして欄だけ残す、はできない。** 実測すると「スロットの幅が合いません
// （値は 1 本、スロットは 0 byte）」で断られ、仮に通っても行どうしの形が揃わない
// （下の命令の表の注記）。「無い」は**値ではなく鍵の不在**で綴る。
for (const p of POSITIONS) {
	const rows = byPos[p];
	if (!rows.length) continue;
	L.push(s("--- " + p + " ---"), "", "#" + p + " :");
	for (const r of rows) {
		L.push(T + s(r.sym) + " :");
		L.push(T + T + "tier : " + r.tier);
		L.push(T + T + "name : " + s(r.name));
		// **結合の向きは真偽ではなく「どちら側か」の添字である。**
		//
		// `[左 右]` を引く添字だと読めば、名前と位置が一致する——左は 0 番目、右は末尾（-1）。
		// 真偽で持つと `0` が真である Sign では条件に直に置けず、明示の比較が要った。
		// 添字なら比較そのものが要らない：段を `[t , (t + 1)] ' assoc` で選べば、
		// **左結合と右結合の違いは「どちら側へ同じ段を渡すか」だけ**になり、分岐が消える。
		if (p === "infix") L.push(T + T + "assoc : " + (r.assoc === "right" ? "-1" : "0"));
	}
	L.push("");
}

// **命令の表——1つの表が両方のバックエンドを養う。**
//
// pass4（JS）と Sign 側のバックエンドは同じ問いを持つ：この演算子はどの命令で出るのか。
// 2箇所に書けば必ず片方だけ直るので、**表が持つ**。アセンブリは文字列の連結で吐くので、
// 要るのは**ニーモニックの綴り**だけである——符号化はアセンブラの仕事である。
//
// ## なぜ意味の表へ欄を足さず、別の表にしたのか
//
// 命令を持つのは中置35個のうち10個である。持たない側をどう綴るかを**実測した**：
//
//     意味の表に欄を足し、無い側は `asm_form : __`
//         → 機械 ✗「スロット asm_form の幅が合いません（値は 1 本、スロットは 0 byte）」
//
// 値が `__` のスロットは 0 byte に測られる。診断が出ること自体より、**その先が大きい**
// ——命令を持つ行は綴り（String は `{ptr,len}` の2本）を持つので 16 byte、持たない行は
// 0 byte になり、**行どうしの形が揃わない**。形が揃っていることだけが実行時の鍵で引ける
// 条件なので、`__` を値に置くやり方は、平らな表にした理由そのものを壊す。
//
// だから**所属の問いとして持つ**。`#strict_infix` と同じく、持つ綴りだけを書いて、無い側は
// 鍵ごと書かない——引けば `__` が返り、それが唯一の偽である。中に書く欄はどの行も同じなので
// 形は揃い、`asm_infix ' tok ' gpr_signed` の二段引きが実機に降りる。
//
// 位置ごとに分けてあるのは意味の表と同じ理由で、綴りが位置をまたいで衝突するからである
// （`-` は中置の `sub` であり前置の `negate` でもある）。いまは中置しか命令を持たない。
//
// 欄の名前が鍵の階層を平らにしている（`asm.gpr.signed` → `gpr_signed`）。機械のクラス
// （`gpr`）を名前に残してあるのは、浮動小数を出す日に `fp_signed` が隣へ並べるためで、
// 層の欄は置かない——層は `fp`・`simd` という名前が既に言っている。
for (const p of POSITIONS) {
	const rows = byPos[p].filter((r) => r.asm);
	if (!rows.length) continue;
	L.push(s("--- " + p + " の命令 ---"), "", "#asm_" + p + " :");
	for (const r of rows) {
		L.push(T + s(r.sym) + " :");
		L.push(T + T + "form : " + s(r.asm.form));
		L.push(T + T + "gpr_signed : " + s(r.asm.gpr.signed));
		L.push(T + T + "gpr_unsigned : " + s(r.asm.gpr.unsigned));
	}
	L.push("");
}

// **曖昧でない中置でないものは書かない。** 所属の問いなので、綴りを鍵にした**集合**で持つ
// ——無ければ `__` が返り、`__` は唯一の偽だから、そのまま条件に置ける。
//
// 以前は 1/0 を全綴りぶん書いていた。**Sign では `0` は真である**ため、`strict ' s~` を条件に
// 直に置くと曖昧でない中置でないものまで真になる。それを避けるには `= 1` と明示するしか
// なく、書く側が毎回その罠を覚えている必要があった。0 を書かなければ罠ごと消える。
//
// 右結合も同じ理由で集合だったが、いまは `assoc` の欄が**添字**として持っている（上の注記）
// ——真偽ではなく `[左 右]` のどちら側かなので、`0` が真であることと衝突しない。
L.push(
	s("--- 曖昧でない中置：前後に空白を入れてよいもの ---"),
	s("前置・後置・囲みにもなる綴りは入っていない"),
	s("| と || は囲みの区切りでもあるので入れない——空白を入れるとノルムが壊れる"),
	s("所属の問いなので綴りを鍵にした集合で持つ。無ければ __ が返る"),
	"",
	"#strict_infix :",
	...strict.map((x) => T + s(x) + " : 1"),
	""
);

