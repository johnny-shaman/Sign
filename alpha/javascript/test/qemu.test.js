// 連結の単位元だからで、その `__` が字面であっても、範囲外の添字が返したものであっても
// 同じでなければならない。字面はパスの上で落としてあったが、**実行時に `__` になった
// ものはそのまま並んでいた**——`` g : s ? `<` (s ' 5) `>` `` が解釈器 2 文字、機械 3 文字
// （範囲外の要素として NUL が1バイト）で、診断はゼロだった。
