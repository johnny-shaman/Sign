	//
	// **自己か相互かは実装側の区別だった。**
	const MREC = "a : [c ~r] ?\n\tc = `q` : c (b r)\n\tc (a r)\nb : [c ~r] ?\n\tc = `q` : c (a r)\n\tc (b r)\n";
