agree("条件が真", "f : x ?\n\tx = 1 : 10\n\t20\nf 1");
agree("条件が偽", "f : x ?\n\tx = 1 : 10\n\t20\nf 2");
agree("尽きたら __", "f : x ?\n\tx > 10 : 1\nf 7");
