	agree("既定の引数が __", "g :\n\t\ts\n\t\tc : s ' 9\n\t? `<` c `>`\n||g `ab`||");
	agree("既定の引数が範囲内（対照）", "g :\n\t\ts\n\t\tc : s ' 0\n\t? `<` c `>`\n||g `ab`||");
