// 解釈器は束縛に読んで `f -1` にも 42 を返していた——今は compile が止める。字下げした同じ
// 枝は、通れば値、尽きれば `__` である。
agree("1本の枝が通る", "f : x ?\n\tx > 0 : 42\nf 5");
agree("1本の枝が尽きる（負の実引数）", "f : x ?\n\tx > 0 : 42\nf -1");
