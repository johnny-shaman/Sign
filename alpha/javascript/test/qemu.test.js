	// `__` とも合流する（`__` は幅を持たないので、揃えるのは器の側だけ）。
	agree("直和と __ の三つ巴", "h : n s ?\n\tn > 2 : `z`\n\tn > 1 : __\n\ts\nf : n ? (h n `xy`) ' 0\nf 5");
