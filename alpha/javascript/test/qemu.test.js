// 括弧が要らない代わりに、関数を演算子の右へ置くときは括る。
agree("階乗（末尾でない再帰）", "f : n ?\n\tn = 0 : 1\n\tn * (f (n - 1))\nf 10");
agree("引数側は括らなくてよい", "f : n ? n * 2\nf 3 + 4");

