const __dirname = path.dirname(fileURLToPath(import.meta.url));
// **インポートを解く手段は呼ぶ側が渡す**（build_system.md §4.2）。`parser.sn` が演算子表を
// 読むようになったので、実機のハーネスでも渡す。
const readImport = (p) => fs.readFileSync(path.join(__dirname, "..", "..", "sign", p), "utf8").replace(/\r\n/g, "\n");
const parser = peggy.generate(fs.readFileSync(path.join(__dirname, "..", "sign.pegjs"), "utf8"));

if (!available()) {
	console.log(`ツールチェーンが無いので飛ばす（${toolReport()}）`);
	console.log("\n0/0 passed");
	process.exit(0);
}

let passed = 0;
let total = 0;

// インタプリタ側の答え。観測境界を通した姿で見る。
function interp(source, charset = "ascii") {
	const { nodes } = compile(source, { parse: parser.parse, charset, readImport });
	const env = newRuntimeEnv(null, charset);
	let r = UNIT;
	for (const node of nodes) r = evaluate(node, env);
	if (isUnit(r)) return "__";
	const o = observe(r);
	if (o === undefined || o === null) return "__";
	// **`Char` は符号位置である**（`String ≅ List(0u)`）。インタプリタは読める姿で
	// 1文字を返すが、機械の側にあるのは数である。同じ値の別の見せ方なので揃える。
	if (typeof o === "string" && [...o].length === 1) return String(o.codePointAt(0));
	// **恒等射（`!__`）は機械の上では `0`（真）である。** インタプリタは射そのものを
	// 返すが、値として運ばれるぶんには「`__` でない」ことしか意味を持たない。
	if (o && typeof o === "object" && o.__identity__) return "0";
	return String(o);
}

// 機械側の答え。`_.main` の x0 を符号付き64ビットで読む。
// **層は指定できる。** 既定は 1（RAM が開通した層）だが、MMIO の番地を算術する形は
// layer 0 の特権なので、そこだけ 0 で回す（上の層では番地の捏造になるため門番が止める）。
function machine(source, charset = "ascii", layer = 1) {
	const { nodes, env } = compile(source, { charset, readImport });
	const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset, layer });
	if (r.diagnostics.length) return "出せない：" + r.diagnostics[0].message;
	const v = asInt(runAsm(r.text)[0]);
	return v === null ? "__" : String(v);
}

// 同じソースを両方へ通し、答えが一致することだけを見る。**期待値は書かない**——
// 仕様の答えはインタプリタが持っているので、ここで二重に書くと片方だけ直る。
function agree(note, source, charset = "ascii", layer = 1) {
	total++;
	let a, b;
	try {
		a = interp(source, charset);
	} catch (e) {
		a = "解釈で例外：" + e.message;
	}
	try {
		b = machine(source, charset, layer);
	} catch (e) {
		b = "機械で例外：" + e.message;
	}
	if (a === b) {
		passed++;
		console.log(`ok   ${note.padEnd(34)} ${a}`);
	} else {
		console.log(`FAIL ${note.padEnd(34)} 解釈=${a} / 機械=${b}`);
	}
}

/**
 * 出せないものが**名指しされている**ことを見る。黙って別の答えを出していないこと、
 * すなわち「まだ」と言えていることの確認である。
 */
// `reason` を渡すと、名指しの**理由**も見る。別の理由で断っていても「名指しされた」には
// なるので、止まった場所が違うことを見逃す。
// **層は指定できる。** 既定は 1 だが、層で断り方が変わる形（生の番地）は上の層で見る。
function checkNamed(note, source, charset = "ascii", reason = null, layer = 1) {
	total++;
	let msg = "（診断が出なかった）";
	try {
		const { nodes, env } = compile(source, { charset, readImport });
		const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset, layer });
		if (r.diagnostics.length > 0 && reason && !r.diagnostics[0].message.includes(reason)) {
			msg = "別の理由：" + r.diagnostics[0].message;
		} else if (r.diagnostics.length > 0) {
			passed++;
			console.log(`ok   ${note.padEnd(34)} ${r.diagnostics[0].message.replace(/（.*/, "")}`);
			return;
		}
	} catch (e) {
		msg = "例外：" + e.message;
	}
	console.log(`FAIL ${note.padEnd(34)} ${msg}`);
}

/**
 * 機械の側だけを見る。**インタプリタと同じものをモデルしていない場所**で使う——
 * 番地の算術がそれで、インタプリタは参照セル（getter/setter）、機械は整数である。
 * 突き合わせられないので期待値を書くしかない。使うのはここだけに留める。
 */
function machineIs(note, source, want, layer = 1) {
	total++;
	let got;
	try {
		got = machine(source, "ascii", layer);
	} catch (e) {
		got = "機械で例外：" + e.message;
	}
	if (got === want) {
		passed++;
		console.log(`ok   ${note.padEnd(34)} ${got}`);
	} else {
		console.log(`FAIL ${note.padEnd(34)} 期待=${want} / 機械=${got}`);
	}
}

/**
 * **見積もりを外れたときに、外れ方が内側に留まることを見る。**
 *
 * 上界は証明ではなく見積もりなので（`returnSizeBound`）、外れる形は書ける。外れたときに
 * 何が起きるかは `agree` では見られない——インタプリタに上界は無いので、正しい答えを
 * 返してしまい、機械の側とは**必ず**食い違うからである。期待値を書くのも違う：食い違う
 * こと自体は仕様であって、決まっているのは**踏み抜かないこと**の方だけである。
 *
 * だから見るのは値ではなく法である。**書いた個数は、呼ぶ側が取った個数を超えない。**
 * 超えれば `__`（作れなかったものは無い）。踏み抜けば qemu が返って来ないので、
 * 「返って来ること」がそのまま検査になっている。
 */
function withinBound(note, source, cap) {
	total++;
	let got;
	try {
		got = machine(source, "ascii", 1);
	} catch (e) {
		got = "機械で例外：" + e.message;
	}
	const n = Number(got);
	if (got === "__" || (Number.isInteger(n) && n >= 0 && n <= cap)) {
		passed++;
		console.log(`ok   ${note.padEnd(34)} ${got} ≦ ${cap}`);
	} else {
		console.log(`FAIL ${note.padEnd(34)} 上界 ${cap} に対し ${got}`);
	}
}

/**
 * **同じ名前が同じ実体であることを見る。** 値では捕まらない形のためにある。
 *
 * 構造体を使うたびに組み直しても、読み出す値は毎回同じなので `agree` は通ってしまう
 * ——違うのは**実体がいくつできるか**である。`$名前` の指す先も、マージが書き込む先も
 * 「どの実体か」で変わるので、そこは命令の側（`sub sp` の回数）を見るしかない。
 */
function buildsOnce(note, source) {
	total++;
	let got;
	try {
		const { nodes, env } = compile(source, { charset: "ascii", readImport });
		const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset: "ascii", layer: 1 });
		got = r.diagnostics.length ? "出せない：" + r.diagnostics[0].message : (r.text.match(/sub\s+sp, sp/g) || []).length;
	} catch (e) {
		got = "機械で例外：" + e.message;
	}
	if (typeof got === "number" && got <= 1) {
		passed++;
		console.log(`ok   ${note.padEnd(34)} sub sp ${got} 回`);
	} else {
		console.log(`FAIL ${note.padEnd(34)} 組み直している（${typeof got === "number" ? `sub sp ${got} 回` : got}）`);
	}
}

