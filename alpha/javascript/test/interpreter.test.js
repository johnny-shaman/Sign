check("[!= 2,] で 2 以外を選ぶ", run("[!= 2,] [1 2 3 2]~"), [1, 3]);
check("[< 3,] は回帰なし", run("[< 3,] [1 2 3 4]~"), [1, 2]);

// 演算子は構文、`[...]` は関数値——この区別は `|` にも効く。
// 中置なら演算子表のUnit規則（左辺Unit→右辺値）で既定値の補完になるが、
// 関数値へ `__` を渡せば完全性公理が先に効いて崩壊する。ポイントフリーと明示ラムダは一致する。
check("中置 (3 < 2) | 0 → 0（演算子のUnit規則）", run("(3 < 2) | 0"), 0);
check("[| 0] (3 < 2) → __（関数値なので完全性公理）", run("[| 0] (3 < 2)"), "__");
check("明示ラムダも同じ", run("f : x ? x | 0\nf (3 < 2)"), "__");

// ポイントフリー記述の前置/後置版（function_guide.md「前置演算子は`[<op>_]` 後置演算子は
// `[_<op>]`」）。`_`（hole）は既にresolveDensityで普通の前置/後置演算ノードのoperandとして
// 構造化されるため、operandが直接holeならその演算子ノードをpartial（Lambda）とマークする
// だけで済んだ——中置のような複雑な部分適用組み立ては不要。
check(
	"[!_] 2 < 3 → __（2<3全体を1引数として受け取り否定、真の値の否定はUnit）",
	run("[!_] 2 < 3"),
	"__"
);
// `!__`の返値はId射（categorical_truth.md §6）。`1`のような具体値を返すとBoolean型を
// 暗黙に再導入することになるため、「Unitでない何か（引数をそのまま返す恒等射）」である
// ことだけを確認する。
//
// ただし「否定が偽を真に変える」のは**演算子としての `!`** の性質であって、
// 関数値としての `[!_]` の性質ではない。両者は支配する規則が違う：
//   - 演算子 `!` は構文であり、演算子表のUnit欄（右辺Unit → Id射）に従う
//   - `[!_]` は hole_desugaring.md により `$p0 ? !$p0` へ静的に脱糖されたラムダであり、
//     完全性公理（`f __ = __`）に従う
// この区別が無いと、同じ否定が「演算子・ポイントフリー・明示ラムダ」の3通りで
// 別々の答えを返す（実際に `n : x ? !x` だけが `__` を返していた）。
// 第一級の関数から「不動点を持たない自己射」が消えることが、Lawvereの不動点定理の下で
// 自己表現（セルフホスト）と両立するための条件でもある。
checkTrue("演算子 !(5 < 3) → Id射（偽の否定は真。これは演算子の性質）", !isUnit(run("!(5 < 3)")));
check("[!_] (5 < 3) → __（関数値なので完全性公理が支配する）", run("[!_] (5 < 3)"), "__");
check("[!_] __ → __（同上。ラムダにUnitを渡せば崩壊する）", run("[!_] __"), "__");
// Id射は恒等射なので、呼べば引数を素通しする（`!__`はPass2でLambdaに分類されるため、
