check("`ab` 1 → \"ab1\"（String左辺）", run("`ab` 1"), "ab1");
check("1 `ab` → \"1ab\"（String右辺でも同じ）", run("1 `ab`"), "1ab");
check("`123` 123 → \"123123\"（list_model.md §4.4）", run("`123` 123"), "123123");
check("1 2 3 → [1 2 3]（Stringが無ければ従来通りList構築）", run("1 2 3"), [1, 2, 3]);

// ---- 貪欲なポイントフリーにはアリティがある ----
//
// `[* 2,]` は残りアリティ1なので写像（各要素へ1回）、`[*]` は残りアリティ2なので畳み込み
// （隣接を潰す）。どちらも器を1本走査すれば済む。
//
// ところが `[*,]` は残りアリティ2に写像印が付いた形——要素ごとに全要素へ適用するので
// n² の適用と中間の器が要る。**この言語はレイヤー0でアプリカティブを扱わない**ので蹴る。
// 写像の糖衣は3つ組（演算子＋オペランド＋カンマ）しか拾わないため、この形は左辺束縛
// （`[1 -]`）として `,` を演算子と読まれ、カンマが落ちて `[*]` と区別が付かなくなり
// **黙って違う値を返していた**（`[*,] 1 2 3` が `[1 2 3]` のまま）。
{
	const rejects = (src) => {
		try {
			run(src);
			return false;
		} catch (e) {
			return String(e.message).includes("Illegal Function Definition");
		}
	};
	checkTrue("[*,] は蹴る（アプリカティブ）", rejects("[*,] 1 2 3"));
	checkTrue("[+,] も蹴る", rejects("[+,] 1 2 3"));
	checkTrue("束縛でも蹴る", rejects("x : [*,]\nx"));
	// 残りアリティ1（写像）と2（畳み込み）は今まで通り。
	check("[* 2,] は写像（残りアリティ1）", run("[* 2,] 1 2 3"), [2, 4, 6]);
	check("[*] は畳み込み（残りアリティ2）", run("[*] 1 2 3"), 6);
	// 両側の束縛も無傷（`,` を演算子と読む経路を通さない）。
	check("[1 -] は左辺束縛", run("[1 -] 5"), -4);
	check("[- 1] は右辺束縛", run("[- 1] 5"), 4);
}

// ---- ポイントフリーはストリームを食う（合成はストリームのパイプライン） ----
// `f g` は左→右のパイプライン（`(f g)(x) = g(f(x))`）なので実引数は**左の関数**へ渡る。
// 左が貪欲なポイントフリーなら合成全体も貪欲でなければならない（pass2側の判定）。
// さらに、合成の中間は「1個のList値」ではなく**流れていくストリーム**なので、
// 次段が貪欲なポイントフリーなら展開して渡す（interpreter側）。
// 以前は前者を見落として `[2 2 3 4 5]`、後者を見落として `[2 4 6 8 10]` になっていた。
check("[* 2,] [+] 1 2 3 4 5 → 30（写像→畳み込みがストリームで繋がる）", run("[* 2,] [+] 1 2 3 4 5"), 30);
check("[* 2,] [* 3,] 1 2 3 → [6 12 18]（写像→写像）", run("[* 2,] [* 3,] 1 2 3"), [6, 12, 18]);
// 括弧で括るとそこで値（List）に固まるが、**畳み込みは器を1本走査するもの**なので
// それで構わない。以前はここが `[2 4 6 8 10]`（=素通り）で、畳み込むには後置~での展開が
