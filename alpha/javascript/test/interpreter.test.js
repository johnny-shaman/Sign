// 「残りを取る」操作が、書き方の違いで別の型になってはいけない。
check("rest は文字列のまま返る", run("tl : [c ~cs] ? cs\ntl `abc`"), "bc");
check("参照受け（`[~s]`）は文字列全体を受ける", run("whole : [~s] ? s\nwhole `abc`"), "abc");
