// **参照が指すのは呼び出し側が置いた記憶である**（stack_abi.md §4.6「参照で渡すのは
// メモリに置かれているものだけ」）。そこへデフォルトを付けると「渡されなかったら呼ばれた
// 側が器を作る」ことになり、所有が反転する——しかも作る場所は自分のフレーム（alloca）
// なので、返せば宙に浮く。返値の設計が sret（呼び出し側がスロットを提供する）へ向かって
// いるのと逆である。
//
// 裸の rest（`~xs`）は stream＝規則であり（原理3 の表）、既定値として置ける「実体化した
// 列」とは別物なので、やはり書けない。
//
// 以前はここが内部エラー（`lines.flatMap is not a function`）で落ちており、`~xs : 1` の
// ように既定式が平らなときは**名前が `~_` になって黙って通っていた**。
{
	const err = (src) => { try { compile(src); return null; } catch (e) { return e.message; } };
	const cases = [
		["[x ~xs] : [1 2]", "f :\n\t[x ~xs] : [1 2]\n?\n\tx\nf __"],
		["[~xs] : [1 2]", "f :\n\t[~xs] : [1 2]\n?\n\txs\nf __"],
		["~xs : [1 2]", "f :\n\t~xs : [1 2]\n?\n\txs\nf __"],
		["~xs : 1（平らな既定式）", "f :\n\t~xs : 1\n?\n\txs\nf __"],
	];
	for (const [note, src] of cases) {
		checkTrue(note + " は構文エラー", /デフォルト値は書けません/.test(err(src) || ""), String(err(src)).slice(0, 60));
	}
	// 裸の仮引数のデフォルトは今まで通り書ける（値はレジスタか .rodata に在るので、
	// 作る場所の問題が起きない）。
	check("裸の仮引数のデフォルトは通る", err("f :\n\tn\n\tas : 0\n?\n\tas\nf 3"), null);
	check("分解の形そのものは通る", err("f : [x ~xs] ? x\nf [1 2]"), null);
}

// ---- 中置 `#`（ストア） ----
//
// **守るのは左辺である。** 演算子表の Unit 欄は「左辺がUnit」「右辺がUnit」に分かれており、
// 危険なのは前者——`$__ # expr` と `$(0x80 < 0x40) # expr` は「致命的なエラー（不正な
// アドレスへの書き込み）」と guide の演算子表が名指ししている。
//
// **右辺の `__` は書ける。** 書けないと**場所を空にできない**——ストリームが尽きたときに
// カーソルへ「もう無い」を書き込めず、次の読み出しが古い値を返す。`$__ = __ = @__` が
// 不動点である以上、`__` は書いて読み戻せる値である。
{
	check("値は書ける", run("x : 1\n$x # 5\n@$x"), 5);
	check("`__` を書けば空になる", run("x : 1\n$x # __\n@$x"), "__");
	check("書き込み先でなければ書かない", run("(5 # 9) | 0"), 0);
}
// **返すのはアドレスである**（同表「アドレスにデータを入れ、成功したらアドレスを返す」）。
// 値を返すと「書けたが値が `__`」と「書けなかった」が区別できず、連鎖もできない。
{
	// 書き込み先でなければ `__` なので、`|` で拾える。
	check("書き込み先でなければ __", run("(5 # 9) | 0"), 0);
	// 書けなくてもアドレスは返る——だから「書けなかった」と「値が __ だった」が混ざらない。
	checkTrue("`__` を書いてもアドレスは返る", run("x : 1\n($x # __) | 0") !== 0);
}
console.log(`\n${passed}/${total} passed`);
process.exit(passed === total ? 0 : 1);
