// **`String ≅ List(0u)` は分割代入にも届く（type_system.md §2）。**
//
// 添字（`s ' 0`）と要素数（`|s|`）は以前から文字列を文字のリストとして扱っていたが、
// ブラケット分割代入だけが文字列を単一の不透明な値として扱っており、同型が片側でしか
