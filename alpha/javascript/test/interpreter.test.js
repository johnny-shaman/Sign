// get_prop（`'`）: 右辺の識別子を「名前」と読むか「値（添字）」と読むかは**左辺が決める**。
//
// type_system.md §2 は「名前付きスロット（`[key : val]`）と連番スロット（`1, 2, 3`）は
// 同じ構造であり、名前の有無だけが違う」と規定している。区別の基準は名前を持つかどうかで
// あり、それは左辺の形にしか無い情報である。
//
// 以前は左辺を問わず常に名前として扱っていたため、§2 が OK 例として明示している
// `list ' i`（`i` は実行時変数でよい）が書けなかった。連番スロットは「順序が意味そのもの」
// であり、変数で引けなければバイト並びを扱う手段にならない。
check(
	"d ' foo → 1（名前付きスロットなら右辺の識別子はキー名）",
	run("d : [\n\tfoo : 1\n\tbar : 2\n]\nd ' foo"),
	1
);
check("d ' bar → 2（同上、2件目のキー）", run("d : [\n\tfoo : 1\n\tbar : 2\n]\nd ' bar"), 2);
check("l ' i → 2（List なら右辺の識別子は値＝添字、§2 の OK 例）", run("l : [1 2 3]\ni : 1\nl ' i"), 2);
check("仮引数経由でも同じ（f : n ? l ' n）", run("l : [1 2 3]\nf : n ? l ' n\nf 2"), 3);
check("連番スロット（カンマ直積）も変数で引ける", run("i : 2\n(1 , 2 , 3) ' i"), 3);
check("String も同じ（文字の List と同型）", run("s : `abc`\nn : 1\ns ' n"), "b");
// 名前付きスロットへの実行時インデックスは §2 が「原理的にコード生成できない」としている
// （添字が静的に確定しないとスロットの型が決まらず命令が選べない）。名前として引かれ、
// そのキーが無いので `__` に収束する。
check("名前付きスロットは変数で引けない（`i` というキーを探して __）", run("s : [\n\ta : 1\n]\ni : 0\ns ' i"), "__");

// 名前付きスロットは **名前・連番・実データ** の三つを持つ。名前で引くのは右辺が識別子の
// とき、連番（宣言順）で引くのは右辺が数値のとき。連番は物理オフセットの順（名前ソートの
// 正規順、stack_abi.md §7.1）とは別物である。
//
// `point == point2` が真でありながら `point ' 0` と `point2 ' 0` が違う値になるのは
// 矛盾ではない。`==` は Hom集合の一致であって**同一性ではない**（同一性は `===` と
// `' !__` が担う、§6.2）。宣言順は `==` が比較していない別の性質であり、それを測って
// 違う値が出るのは正しい観測である。
{
	const P = "point : [\n\tx : 3\n\ty : 4\n]\n";
	const Q = "point2 : [\n\ty : 4\n\tx : 3\n]\n";
	check("point ' 0 → 3（連番は宣言順）", run(P + "point ' 0"), 3);
	check("point ' 1 → 4", run(P + "point ' 1"), 4);
	check("point ' -1 → 4（負の連番は末尾から）", run(P + "point ' -1"), 4);
	check("point ' 2 → __（範囲外）", run(P + "point ' 2"), "__");
	check("point ' x → 3（名前でも引ける）", run(P + "point ' x"), 3);
	check("|point| → 2（スロット数。連番で引ける以上、個数も定義されている）", run(P + "|point|"), 2);
	check("point2 ' 0 → 4（宣言順が違えば違う値。正しい観測）", run(Q + "point2 ' 0"), 4);
	check("それでも == は真（Hom集合の一致は宣言順を問わない）", run(P + Q + "point == point2"), { x: 3, y: 4 });
}

// 未定義識別子のUnit収束は診断上informationとして記録される（unit.md §0.1、非ブロッキング）。
function runDiag(source) {
	const { nodes } = compile(source, { parse: parser.parse });
	const runtimeEnv = newRuntimeEnv(null);
	let result = UNIT;
	for (const node of nodes) result = evaluate(node, runtimeEnv);
	return { result, diagnostics: runtimeEnv.diagnostics };
}

function checkTrue(note, cond) {
	total++;
	if (cond) {
		console.log(`OK   ${note}`);
		passed++;
	} else {
		console.log(`FAIL ${note}`);
	}
}

function checkThrows(note, fn) {
	total++;
	try {
		fn();
		console.log(`FAIL ${note}`);
		console.log(`     例外が投げられなかった`);
	} catch (e) {
		console.log(`OK   ${note}`);
		passed++;
	}
}

{
	const { result, diagnostics } = runDiag("tick");
	checkTrue("未定義識別子 tick → __ に収束しつつ例外を投げない", isUnit(result));
	checkTrue(
		"未定義識別子 tick → diagnosticsに1件、level='information'（仮想キーワード利用を委縮させないためwarningへ格上げしない）",
		diagnostics.length === 1 && diagnostics[0].level === "information" && diagnostics[0].identifier === "<tick>"
	);
}

{
	const { diagnostics } = runDiag("x : 5\nx + 1");
	checkTrue("定義済み識別子 x の参照 → diagnosticsは空", diagnostics.length === 0);
}

