// 「等しくない」ことが確定して真になり、真のときに情報を運ぶのは非Unit側の値なので
// そちらを返す。以前は左辺Unitだけ吸収元にしており、`5 != __` が 5 を返すのに
// `__ != 5` は `__` という非対称になっていた——同じ演算子が引数の順序で挙動を変えていた。
