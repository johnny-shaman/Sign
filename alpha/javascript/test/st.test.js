/**
 * SignType（`.st` / `.ist`）生成の動作確認（type_system.md §6）。
 *
 * 型は「宣言」されるものではなく「コードから読み取って書き写す」だけの存在であり（§1）、
 * `.st` はその書き写しである。同時にこれは**型システムに対する最初の観測手段**でもある
 * ——消費者が居ないうちは、間違った型も欠けた型も観測されないままになる。
 *
 * ここで固定するのは**仕様が要求する形**だけである。実装がまだ仕様へ届いていない部分は
 * 何も表明しない（下の「返値型について」を参照）。壊れている挙動を期待値に書くと、
 * それが正しい仕様であるかのように見えてしまうためである。
 *
 * 実行: node test/st.test.js（`npm test` からも呼ばれる）
 */
import { compile } from "../compile.js";
import { generateSignType } from "../st.js";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

let passed = 0;
let total = 0;

// 生成結果からコメント行と空行を除いた本文だけを取り出す。
function entries(source, scope = "ist") {
	const { nodes, env } = compile(source);
	const r = generateSignType(nodes, env, { scope });
	return r.text
		.split("\n")
		.filter((l) => l && !l.startsWith("`"))
		.map((l) => l.trim());
}

// 未解決として数えられた箇所の数。
function holes(source, scope = "ist") {
	const { nodes, env } = compile(source);
	return generateSignType(nodes, env, { scope }).unresolved;
}

function check(note, got, want) {
	total++;
	const ok = JSON.stringify(got) === JSON.stringify(want);
	if (ok) {
		console.log(`OK   ${note}`);
		passed++;
	} else {
		console.log(`FAIL ${note}`);
		console.log(`     got:  ${JSON.stringify(got)}`);
		console.log(`     want: ${JSON.stringify(want)}`);
	}
}

// ---- 書き写せている型 ----
check("Atom はリテラルの Layer 2 型がそのまま出る", entries("pi : 3.14"), ["pi : Float"]);
check("String も同様", entries("greeting : `hello`"), ["greeting : String"]);
check("本体が式なら返値型が出る", entries("f : x ?\n\tx > 3 : 1\n\t2"), ["f : Int -> Int"]);
// §7.1 の表がそのまま述べている: `f : x y ? x + y` の `x`/`y` は `+` のシグネチャが
// 要求する `Scalar` であり、`f` は `Lambda<returns: Scalar>` になる。ここで言う `Scalar` は
// 「String を含まない Atom」という**族**（§4 の記法定義）であって Layer 2 の具体型では
// なく、呼び出しサイトで具体化されるまでの暫定形である。
check("仮引数の型を本体の演算子から逆算し、返値まで通る（§7.1）", entries("add : a b ? a + b"), [
	"add : Scalar Scalar -> Scalar",
]);
// 相手がリテラルなら、族（`Scalar`）ではなくその型まで決まる。Sign には型注釈の構文が
// 無いので（§1「型はコードの影」）、初期化時に型を決めたいときは**値を変えない演算**を
// 書く。リテラルは**左辺**に置く——域を選ぶのは左辺だからである（§3.2）。
// `0 +` は Int、`0x0 +` は Address、`0.0 +` は Float。実行時コストは無いが型は固定される。
check("相手が整数リテラルなら Int まで決まる", entries("f : x ? x + 1"), ["f : Int -> Int"]);
check("`0.0 +` は恒等演算だが型を Float に固定する（域を選ぶのは左辺、§3.2）", entries("f : x ? 0.0 + x"), ["f : Float -> Float"]);
check("比較演算子でも同じ", entries("f : x ? x > 3"), ["f : Int -> Int"]);
check("比較は同種同士なので String も決まる", entries("f : t ? t = `abc`"), ["f : String -> String"]);
check("相手もリテラルでなければ族までしか言えない", entries("add : a b ? a + b"), ["add : Scalar Scalar -> Scalar"]);
check(
	"`'` でアクセスしたフィールドを要求集合として集める（§6.2）",
	entries("distance : p1 p2 ? p1 ' x - p2 ' x").map((l) => l.split("->")[0].trim()),
	["distance : {x} {x}"]
);
check(
	"分岐で違うフィールドを見たら和集合になる（§6.2 の NOTE）",
	entries("f : p ?\n\tp ' x : p ' y\n\tp ' z").map((l) => l.split("->")[0].trim()),
	["f : {x, y, z}"]
);
check("ブラケット分割代入は形をそのまま書く", entries("f : [h ~t] ? h").map((l) => l.split("->")[0].trim()), [
	"f : [h t~]",
]);

// ---- 名前付きスロットと連番スロット（§2） ----
//
// 両者は同じ構造（固定オフセットで並ぶ連続ブロック）だが**関心事が違う**。
// 名前付きは「何が在るか」が関心事で、物理オフセットは名前でソートした正規順に
// 割り当てられる（stack_abi.md §7.1）——ただしその順序は言語から観測できない。
// `==` は Hom集合の一致で宣言順を問わず、位置アクセスも持たない。
// 連番は「どこに在るか」が関心事で、宣言順がそのまま物理配置になる。
// バイト並びを書くのはこちらであり、MMIO のようにハードウェアが配置を決める場面で使う。
// 名前付きスロットの型は、それ自体が名前付きスロットの形をしている（名前→連番の写像）。
// **並び＝物理配置**（名前ソートの正規順、stack_abi.md §7.1）、**各名前が持つ値＝宣言順**。
// 両方が明示され、どちらも導出に頼らない。
//
// 宣言順を型の側で保存することには実務上の必然がある——`point ' 0` のような連番アクセスは、
// 連番→名前→ソート済みオフセットと辿って初めてコンパイルできる。型が宣言順を捨てると
// この経路が失われ、位置アクセスが解決不能になる。
//
// `point` と `point2` は `==` では等しい（Hom集合の一致は宣言順を問わない）が、連番で
// 引けば違う値を返す。それは `==` が比較していない性質を測っているだけであり矛盾ではない。
// どちらのスロットも (型, 連番) を持つ。違いは連番の書き表し方だけである——連番スロットは
// 名前が無いので並べ替える鍵が無く、記法上の位置がそのまま連番になる（だから書かない）。
// 名前付きは名前でソートして並べるため、連番は明示するしかない（`型 , 連番` の直積）。
check("名前はソート順に並び、各名前が (型, 連番) を持つ", entries("p : [\n\tx : 1\n\ty : 2\n]"), [
	"p : Struct{x : Int , 0  y : Int , 1}",
]);
check("宣言順が違えば連番が入れ替わる（ねじれが型に保存される）", entries("p : [\n\ty : 2\n\tx : 1\n]"), [
	"p : Struct{x : Int , 1  y : Int , 0}",
]);
// 並びと連番が食い違う例。宣言は CR→SR→DR だが物理配置は CR→DR→SR になる
// ——名前付きスロットに位置の確約が無いこと（stack_abi.md §7.1）が型に現れている。
check("ねじれもスロット型も1行で読める", entries("uart : [\n\tCR : 0x40011000\n\tSR : 0\n\tDR : \\d\n]"), [
	"uart : Struct{CR : Address , 0  DR : Char , 2  SR : Int , 1}",
]);
check("連番スロットは順序どおりにスロット型を並べる", entries("t : 1 , `abc` , 2.5"), [
	"t : Struct(Int String Float)",
]);
// List は要素型を伴って `List(T)` と書く。要素型を落とすと「整数のリスト」と「実数の
// リスト」が同じ `List` になり、単一の実数（`Float`）とも区別が付かなくなる。要素型は
// Pass 4 が `base + i × sizeof(T)` を出すのに要る情報であり、最も落としてはいけない。
check("List は要素型を伴う（整数のリスト）", entries("l : [1 2 3]"), ["l : List(Int)"]);
check("実数のリストは区別される", entries("l : [1.0 2.0]"), ["l : List(Float)"]);
check("単一の実数とも区別される", entries("r : 5.0"), ["r : Float"]);
// 前置 `~`（持ち上げ）は**長さ1の器**を作る。`$`/`@` が単体値に対する持ち上げ／持ち下げ
// であるのと同じ段で、前置 `~`／後置 `~` が列に対するそれを担う。
//
// 以前ここは `Implicit(T)`（暗黙のアドレス＝場所）だった。その名前は「番地を型として
// 名指す」ことに意味があった頃のものだが、**番地は表に出さないと決めた**——`$` が作った
// 番地は算術に使えず、読むなら `@`、列を辿るなら `[h ~t]` の分解で語る。観測できない
// ものを名指す型には仕事が残っておらず、観測できる姿は長さ1の器＝`List` だけである
// （`~x ≅ [x]`）。実害も出ていた：`Implicit` は要素型が1段ずれるので `~5 ' 0` が要素
// ではなく器そのものを返し、`||~[1 2 3]||` は型が 1・値が 3 と食い違っていた。
//
// 持ち上げは**型が決まったものに対して行う**。`~@p + 0.0` は `(~@p) + 0.0` に切れて
// `List + Float` になり §3.2 で `__` へ潰れるので、`~(@p + 0.0)` と書く。`$` が
// `$[array ' 0]` のように確定した式へ適用されるのと同じ形。
check("前置 `~` はスカラーを長さ1の器へ持ち上げる", entries("p : 0x40011000\nlevel : ~(@p + 0.0)"), [
	"p : Address",
	"level : List(Float)",
]);
// **器に当てれば恒等。** `~` は η であり `[x] ≅ x` の潰れが効くので、器に当てても何も
// 増えない（`Implicit(List)` のような「器を要素に持つ器」にはならない）。冪等でもある。
check("列を持ち上げても列のまま", entries("l : ~[1 2 3]"), ["l : List(Int)"]);
check("文字列も同じ", entries("s : ~`abc`"), ["s : String"]);
check("持ち上げは冪等", entries("a : ~~5"), ["a : List(Int)"]);
// **読んだものは `Raw` である**——値は在るが型が無い。以前ここは `Address` を名乗って
// おり、「読んだのは番地だ」という主張になっていた（読んだのが 65 でも）。
//
// `Raw` は格子の**最弱**なので、具体型と出会えば必ずそちらが勝つ。だから位置に依らず
// 答えが同じで、**可換が保たれる**——`@p + 0` も `0 + @p` も `Int` である。左辺優先が
// 働くのは「強弱が無いとき」だけで、型を持たないものには主張すべき内容が無い。
check("読み出しに 0 を足すと Int（Raw は具体型に負ける）", entries("p : 0x40011000\nraw : @p + 0"), [
	"p : Address",
	"raw : Int",
]);
check("足す向きを変えても同じ（可換）", entries("p : 0x40011000\nraw : 0 + @p"), [
	"p : Address",
	"raw : Int",
]);
// 持ち上げた結果への算術は成立しない。場所は Scalar ではないので射が無く、零射へ落ちる
// （§4）。前置 `~` は他の前置演算子と同じく最も内側で結合する（tier 23）ため、
// `~xs + 1` は `(~xs) + 1` になる——これが「持ち上げは型が決まったものに対して行う」を
// 構文の側から強制している。
check("持ち上げた結果への算術は __ へ落ちる", entries("xs : [1 2 3]\nbad : ~xs + 1"), [
	"xs : List(Int)",
	"bad : Unit",
]);

// 1要素のリストはスカラーと同型なので `List(T)` にならない（`[5]` は `Int`）。
// 設計上の同一視であり欠落ではない。
//
// **ただし同型なのは意味であって表現ではない。** `stack_abi.md` §4.6 では `List` は
// `{ptr, len}` で渡り、スカラーは値そのものがレジスタに乗る——ビット列は違う。
// スカラーが `List` を要求する位置へ流れるときは、Pass 4 が1要素ぶんの連続領域を
// 作って渡すことになる（同型は保たれるが、変換は無料ではない）。
check("1要素のリストはスカラーと同型", entries("one : [5]"), ["one : Int"]);
// 入れ子でも要素型が保たれる。
check("連番スロットの中でも要素型が残る", entries("t : 1 , [1 2] , [1.0 2.0]"), [
	"t : Struct(Int List(Int) List(Float))",
]);

// ブロック記法は1行のカンマ形と同じ型になる（list_model.md §3.1 の IMPORTANT）。
// 改行とタブだけで次元が上がるので、行末のカンマは要らない。
check("ブロックの行が次元の行になる", entries("s :\n\t1 2\n\t3 4"), ["s : List(List(Int))"]);
check("1行のカンマ形と一致する", entries("s : 1 2 , 3 4"), ["s : List(List(Int))"]);
check("3次元まで通る", entries("v3 :\n\t1 2 , 3 4\n\t5 6 , 7 8"), ["v3 : List(List(List(Int)))"]);
check("行が揃わなければ Struct", entries("L :\n\t1 2\n\t3 4 5"), ["L : Struct"]);


// **裸の仮引数は、証拠が何も無くても `Atom` まで書ける。**
//
// 裸の仮引数（rest でもブラケット分割代入でもない）は1個の値を受ける。集合を受け取るなら
// `[x ~xs]`（参照渡し）か `~xs`（stream）で宣言するので、宣言の形が既に「点である」ことを
// 語っている（原理3 の表）。さらにデフォルトが無ければ `__` を渡せない——完全性公理により
// 呼び出しごと潰れるので、本体に入った時点で非Unitが保証される。
//
// `Atom` は §4 の記法定義で「String を**含む**スカラー」＝ `Scalar | String` である。
// 多相に見えて下限が決まっている。具体的な型は呼び出しサイトで確定する（§5 Pass 1b）。
check("証拠が無くても裸の仮引数は Atom", entries("f : x ? x"), ["f : Atom -> Atom"]);
check("演算子から逆算できればそちらが優先", entries("f : x ? x + 1"), ["f : Int -> Int"]);
// rest は stream、ブラケットは構造であり、どちらも点ではないので `Atom` は付けない。
check("rest には付けない", entries("f : x ~xs ? x"), ["f : Atom _~ -> Atom"]);
check("ブラケットにも付けない", entries("f : [a ~b] ? a"), ["f : [a b~] -> Atom"]);
// **デフォルト式があれば、その型がその仮引数の型である。**
//
// デフォルトは「引数が省略されたときに実際にそこへ入る値」なので、型の根拠として本体の
// 使用箇所より強い。使用箇所は「その演算が要求する型」しか語らない——`y + 0.0` は y が
// Int でも昇格するので y が Float とは限らない。デフォルトは中身そのものを語る。
check("デフォルトが整数なら Int", entries("f :\n\tx\n\ty : 1\n? y"), ["f : Atom Int -> Int"]);
check("デフォルトが実数なら Float", entries("f :\n\tx\n\ty : 1.0\n? y"), ["f : Atom Float -> Float"]);
check("デフォルトが1文字なら Char", entries("f :\n\tx\n\ty : \\s\n? y"), ["f : Atom Char -> Char"]);
check("デフォルトがリストなら List", entries("f :\n\tx\n\ty : [1 2 3]\n? y"), ["f : Atom List -> List"]);
check("デフォルトは使用箇所より優先する（値は Int、式が Float へ昇格）", entries("f :\n\ty : 1\n? y + 0.0"), [
	"f : Int -> Float",
]);
// ---- 返値型（§7.1・§7.3・§8） ----
//
// 関数本体（match_case の並び）の型は各 arm の型の**直和**であり（§7.3）、apply の結果型は
// **呼び先の返値型**である（§7.1）。Lambda 自身は Layer 1 のカテゴリで Layer 2 型を持たない
// （§2）が、射の適用結果は場所を持つ値なので型を持つ——だから返値型は Layer 2 の型表では
// なく識別子テーブル側（binding.returns）に置く。
//
// 再帰関数の返値型は自分自身に依存するため一度の走査では決まらない。**`__` を束の底**
// として始める：零対象は直和の単位元なので、初回は再帰呼び出しの枝が何も寄与せず基底
// ケースだけが型を決める。次の周回でその型が再帰の枝へ伝わり、変化が止まったところが
// 返値型である。型変数も制約ソルビングも使っていない（§1）——束を単調に上がるだけ。
check("arm の型が割れたら直和になる（§7.3）", entries("f : n ?\n\tn = 0 : `zero`\n\tn"), [
	"f : Int -> Int | String",
]);
// `__` の arm は直和から落ちる。完全性公理により全ての関数が `__` を返しうるので
// `T | Unit` は情報を持たない。零対象は余積の単位元でもあり、代数的にも一貫している。
check("`__` の arm は直和から落ちる", entries("f : t ?\n\tt = `abc` : t\n\t__"), ["f : String -> String"]);
check("再帰が解ける（束の底から上がる）", entries("down : n ?\n\tn = 0 : 0\n\tdown (n - 1)"), [
	"down : Int -> Int",
]);
check("再帰でも基底ケースが型を決める", entries("s : n ?\n\tn = 0 : `end`\n\ts (n - 1)"), [
	"s : Int -> String",
]);
check("相互再帰も解ける", entries("ev : n ?\n\tn = 0 : 1\n\tod (n - 1)\nod : n ?\n\tn = 0 : 0\n\tev (n - 1)"), [
	"ev : Int -> Int",
	"od : Int -> Int",
]);
// **実引数の位置が仮引数の型を語る。**
//
// `h : y ? g y` の `y` は `g` が要求する型である。演算子から逆算するのと同じことを、
// 演算子の代わりに**呼び先のシグネチャ**でやっている——どちらも「その位置に置ける型は
// 何か」を読んでいるだけである。返値型と仮引数型は互いに依存するので、同じ不動点で回る。
check("呼び先の要求が実引数へ逆流し、返値も伝わる", entries("g : x ? x + 1\nh : y ? g y"), [
	"g : Int -> Int",
	"h : Int -> Int",
]);
// 多段でも周回のうちに伝わる。
check("多段の逆流", entries("g : x ? 0.0 + x\nh : y ? g y\nk : z ? h z"), [
	"g : Float -> Float",
	"h : Float -> Float",
	"k : Float -> Float",
]);
// ---- 静的・単相化・動的の3層が型に出る ----
//
// `$` は §4 の通り常に `Atom(Address)` を返す。凍結対象が関数でもデータへのパスでも、
// `$` 自身は「その式が指す場所のアドレスを取る」だけで場合分けを必要としない（§2）。
//
// `p : $f` のように「関数のアドレス」を束縛している場合、`@p` の呼び先は `f` である。
// §2 の IMPORTANT が「多くの場合は静的に一意に決まる（`@handler` で handler の定義が
// 既知なら構文から読める）」と述べている分を由来として辿る。
//
// この2つが入ると `_` が「本当に呼び先が静的に決まらない場所」だけに絞られる。
// `dyn` のようなキーワードを書かずに、3層が型として区別できる。
//
//   具体型      完全に静的。命令テンプレートが1つに決まる
//   Atom        定義側では決まらない。呼び出しサイトで具体化される（§5 Pass 1b、単相化）
//   `_`         呼び先が実行時にしか決まらない。**ここが本物の動的ディスパッチ**
check("`$` は常に Address（関数を指しても）", entries("f : x ? x + 1\np : $f"), [
	"f : Int -> Int",
	"p : Address",
]);
check("`p : $f` を経由した `@p x` も呼び先が静的に決まる", entries("f : x ? x + 1\np : $f\ncall : x ? @p x"), [
	"f : Int -> Int",
	"p : Address",
	"call : Atom -> Int",
]);
check("`@f x` も同じく解ける", entries("f : x ? x + 1\ncall : x ? @f x"), [
	"f : Int -> Int",
	"call : Atom -> Int",
]);
// 構造体フィールド経由の呼び出しは、呼び先が実行時にしか決まらない——手で書いた vtable
// である。返値は `_` になり、§6.2 の要求フィールド集合 `{h}` が「h というスロットを
// 要求する」ことを示す。両方あわせて vtable スロットのシグネチャになっている。
check("構造体フィールド経由の呼び出しは `_`（本物の dyn）", entries("f : x ? x + 1\nt : [\n\th : $f\n\tk : 0\n]\ncall : s ? @(s ' h) 5"), [
	"f : Int -> Int",
	"t : Struct{h : Address , 0  k : Int , 1}",
	"call : {h} -> _",
]);
// ---- 範囲: `.st` は export されたものだけ ----
check("`.st` は export されていない識別子を出さない", entries("a : 1\nb : 2", "st"), []);
check("`.st` は export 記号を保ったまま出す", entries("#a : 1\nb : 2", "st"), ["#a : Int"]);
check("`.ist` は全識別子を出す", entries("#a : 1\nb : 2", "ist"), ["#a : Int", "b : Int"]);

// ---- 残っている `_` について ----
//
// 返値型そのものは解けるようになった。まだ `_` が出るのは、そもそも**仮引数の型が
// 決まっていない**場合である——型は演算子から逆算するので、算術にも比較にも渡されない
// 引数（リストを受け取って分解するだけ、等）には手掛かりが無い。
//
// これは欠落というより、まだ書いていない規則の裏返しである。`'`（フィールドアクセス）や
// ブラケット分割代入の形からの逆算はまだ実装していない（§6.2 の要求フィールド集合は
// `.st` に出しているが、仮引数の atomType へは反映していない）。

// ---- 合成のシグネチャ（`h : f g`） ----
//
// 合成は Lambda なので Layer 2 の Atom 内部型を持たない。それでも `.st` には型が出る
// ——スペースによる合成は左→右のパイプライン（`f g` は `g(f(x))`、coproduct_resolver.md
// §3.1）なので、**仮引数は左端の関数が、返値は右端の関数が**決めるからである。
check("合成のシグネチャは両端から決まる", entries("f : x ? x + 1\ng : x ? x * 2\nh : f g"), [
	"f : Int -> Int",
	"g : Int -> Int",
	"h : Int -> Int",
]);
check("両端の型が違えば、そのまま左端の仮引数と右端の返値になる", entries("f : x ? 0.0 + x\ng : x ? x > 3\nm : f g"), [
	"f : Float -> Float",
	"g : Int -> Int",
	"m : Float -> Int",
]);
// 多段合成でも決めるのは両端だけである（間の関数は型の受け渡しにしか関与しない）。
check("多段合成でも両端が決める", entries("f : x ? 0.0 + x\ng : x ? x * 2\nk : x ? x = \\s\nc : f g k"), [
	"f : Float -> Float",
	"g : Int -> Int",
	"k : Char -> Char",
	"c : Float -> Char",
]);
// その場に書かれた無名ラムダは端としてそのまま使える。
check("合成の端が無名ラムダでも解ける", entries("f : x ? x + 1\nh : (x ? 0.0 + x) f"), [
	"f : Int -> Int",
	"h : Float -> Int",
]);
// ポイントフリーのブロック（`[+ 1]`）は演算子表からシグネチャが出るので端として辿れる
// ——`operator_table.md` の基本原則が言う通り、演算子表はそれ自体が型の表である。
check("ポイントフリーの端も解ける", entries("g : x ? x * 2\nh : [+ 1] g"), [
	"g : Int -> Int",
	"h : Int -> Int",
]);
// `@p`（アドレス経由の間接呼び出し）は呼び先が静的に決まらないので辿れない。
// 分からないことを「分かった」と書かないのが `.st` の原則なので `_` のままにする。
check("辿れない端を持つ合成は `_` のまま", entries("f : x ? x + 1\np : $f\nh : f @p"), [
	"f : Int -> Int",
	"p : Address",
	"h : _",
]);


// ---- 部分適用のシグネチャ（`g : f 1`） ----
//
// 部分適用も Lambda なので Layer 2 型を持たないが、シグネチャは呼び先から決まる
// ——**渡した分だけ仮引数が減り、返値は変わらない**。Pass 2 が静的にアリティ不足を
// 判定して `partial_apply` を立てているので（§5）、残りの仮引数を数え直すだけでよい。
check("部分適用は渡した分だけ仮引数が減る", entries("f : x y z ? x + y + z\ng : f 1"), [
	// スロットは呼び出しサイトで具体化されている——**部分適用も呼び出しサイトである**。
	// 飽和していなくても、埋めたスロットについては同じ強さの証拠になる（`f 1` の 1 は Int）。
	"f : Int Scalar Scalar -> Scalar",
	"g : Scalar Scalar -> Scalar",
]);
check("2個渡せば2個減る", entries("f : x y z ? x + y + z\ng : f 1 2"), [
	// 3つ目も Int になる——§3.2「域を選ぶのは左辺」により、`(x + y)` が Int である以上
	// その右辺に置ける `z` も Int である。左辺の型注釈は2項目以降へも伝わる。
	"f : Int Int Int -> Int",
	"g : Int -> Int",
]);
// 部分適用の結果をさらに部分適用しても辿れる（Lambda を作る式は積み重なる）。
check("部分適用の部分適用も辿れる", entries("add3 : a b c ? a + b + c\ninc : add3 1\nboth : inc 2"), [
	"add3 : Int Scalar Scalar -> Scalar",
	"inc : Scalar Scalar -> Scalar",
	"both : Scalar -> Scalar",
]);
// 返値型は呼び先のまま変わらない——減るのは仮引数だけである。
check("返値は呼び先のまま", entries("f : x y ? 0.0 + x + y\ng : f 1.5"), [
	"f : Float Float -> Float",
	"g : Float -> Float",
]);
// 別名（`alias : f`）も同じシグネチャになる。
check("別名は同じシグネチャになる", entries("f : x ? 0.0 + x\nalias : f"), [
	"f : Float -> Float",
	"alias : Float -> Float",
]);


// ---- ポイントフリー（演算子を直接値として使う） ----
//
// `operator_table.md` の基本原則が「持ち上げる／持ち下げる演算子の関係性が包括的に型を
// 決定する」と言う通り、**演算子表はそれ自体が型の表**である。`[+ 1]` は「`+` の左辺が
// まだ来ていない」形なので、シグネチャは `+` のシグネチャから穴の数を数えるだけで出る。
//
// 規則は `f : x ? x + 1` を逆算するのと**同一**である——相手がリテラルならその型まで決まり、
// 両方とも空なら演算子が要求する族までしか言えない。同じ結論を2通りの書き方から得ている
// のであって、ポイントフリーのために別の規則を足しているわけではない。
check("片側が埋まっていれば穴は1つ", entries("inc : [+ 1]"), ["inc : Int -> Int"]);

// **貪欲なポイントフリーは穴を数える形ではない。** `[+ 1]` は残りアリティ0（合成済み）
// なので穴を数えれば済むが、`[+]` は残りアリティ2——隣り合う2つを潰していく**畳み込み**
// であり、受け取るのは器1つ、返すのはその要素型である。だから `Scalar Scalar -> Scalar`
// （2引数の関数）ではなく `List(Scalar) -> Scalar` になる。
//
// 畳み込みには名前が要る（自分を呼ぶ）ので、コンパイラが `_pf_fold_<演算子>` として
// トップレベルへ持ち上げる。`.ist` は全識別子を書き写す観測手段なので、その2つも出る
// ——`.st`（公開側）は export されたものだけなので漏れない。
check("貪欲な畳み込みは器を1つ受ける", entries("add : [+]"), [
	"_pf_fold_2b_go : Scalar List -> Scalar",
	"_pf_fold_2b : List(Scalar) -> Scalar",
	"add : List(Scalar) -> Scalar",
]);
check("相手のリテラルが型を決める（実数）", entries("fl : [+ 1.0]"), ["fl : Float -> Float"]);
check("アドレスでも同じ", entries("off : [+ 0x10]"), ["off : Address -> Address"]);
check("比較演算子も同じ規則（値返却型比較）", entries("gt : [> 3]"), ["gt : Int -> Int"]);
check("比較は同種同士なので String も決まる", entries("eq : [= \\a]"), ["eq : Char -> Char"]);
// 構造比較（`==` / `!==`）はリストや構造体にも効くので、要素の族が定まらない。
// 分からないことを「分かった」と書かないのが `.st` の原則なので、仮引数は分割代入の形
// （`[x xs~]`）のまま——要素型を名乗らない——で書き写す。
//
// 比較で畳むのは**連鎖比較そのもの**である。`<` は成立時に右辺を返すので、左から畳めば
// `(1 < 2) < 3` = `2 < 3` となり、中置の `1 < 2 < 3` と同じ道を通る。連鎖が畳み込みの
// 特別扱いではなく、畳み込みの向きが連鎖を生んでいる。
check("構造比較は要素の族を名乗らない", entries("st : [==]"), [
	"_pf_fold_3d3d_go : Atom [x xs~] -> Atom",
	"_pf_fold_3d3d : [x xs~] -> Atom",
	"st : [x xs~] -> Atom",
]);


// ---- ブラケット分割代入の rest は器そのものである ----
//
// `[c ~rest]` は渡された単一の集合をその場で分解する（list_model.md §2.4）。`c` が要素で
// `rest` は**残りの集合**——つまり `rest` の型は器の型と同じである。したがって要素の型が
// 分かれば器の型も決まり、それがスロットの型になる。
//
// 要素が文字（`String`）なら器は `String` である。**`List(String)` という型は存在しない**
// ——文字列同士をスペース（余積）で並べると String の吸収則で1本に連結されるため
// （`` [`ab` `cd`] `` は `"abcd"`）、複数の文字列を保つには `Struct`（カンマ）が要る。
// だから「要素が String な List」と「String」は同じものであり、迷う余地が無い。
check("要素が文字なら器は String", entries("hd : [c ~rest] ?\n\tc = `a` : __\n\tc (hd rest)"), [
	"hd : String -> String",
]);
check("残りを返す形でも同じ", entries("tl : [c ~rest] ?\n\tc = `a` : rest\n\ttl rest"), ["tl : String -> String"]);
check("要素が数値なら器は List(T)", entries("sum : [x ~xs] ? xs & x + (sum xs) | x"), [
	"sum : List(Scalar) -> Scalar",
]);
check("実数なら List(Float)", entries("g : [x ~xs] ? 0.0 + x"), ["g : List(Float) -> Float"]);
// 要素の型が分からなければ形のまま書く。形は「まだ型が分かっていない」ときの記述であって、
// 裸の仮引数における `Atom` と同じ位置にある。
check("証拠が無ければ形のまま", entries("f : [c ~rest] ? c"), ["f : [c rest~] -> Atom"]);
// rest が無いブラケット（`[a b]`）は器の型を決める手掛かりが無い——`rest` こそが器だから。
check("rest が無ければ器は決まらない", entries("f : [a b] ? a + b"), ["f : [a b] -> Scalar"]);

// **添字で書くと返値型を取り違える。**
//
// `(s ' 0) (f (s ' 1~))` は `s ' 0` の要素型が分からず、余積の join が `List` に落ちる
// ——文字列を返す関数なのに `List` と書かれてしまう。分割代入なら `c` が要素だと分かる
// ので String の吸収則が効いて正しく `String` になる。
//
// 引数の側は `Atom`（何も分かっていない）ではなく **`Container`** である。添字は
// 「器である」とは言っている——言っていないのは**どの器か**だけで、そこは呼び出し
// サイトが実引数を見せた時点で狭まる。返値を取り違える理由は変わらない（要素型が
// 分からないこと）が、引数について分かっていることは書けるようになった。
// ---- 器として使われた仮引数は器である（`Container` 族） ----
//
// `st ' 0` も `st~` も、器でなければ書けない——前置 `@` から `Address` を読むのと同じ
// 推論である。ここが無かったために、スタックの API 全体（`top` / `pop` / `push`）の
// 仮引数が `Int` になっていた。初期値が `bottom : 0` というスカラーだったためで、
// **値としては正しく、役割だけが器**だった。
//
// **書くのは族であって具体型ではない。** `List` と決め打つと String の仮引数まで
// `List` になり、要素型が降りられなくなる（layout が無限再帰する）。分かっているのは
// 「器である」ことだけなので、そこまでを書いて呼び出しサイトに狭めさせる。
// 引ける（`Container`）が、何が出るかは言えない（`_`）——器の要素が器とは限らない。
check("実引数が無ければ族のまま", entries("f : st ? st ' 0"), ["f : Container -> _"]);
check("撒く形でも器だと分かる", entries("f : st d ? d st~"), ["f : Container Atom -> List"]);
// 狭まるのは引数の側である。**要素型も裸の仮引数へ届く**——かつてここは `_` のままで、
// 「分割代入（`[c ~rest]`）にはその仕組みがあるが、裸には無い。ここは次の穴である」と
// 書いてあった。埋めた。器を受け取る位置は、ブラケットで受けようが裸で受けようが同じ
// だけ要素の型を語る。
//
// 落ちていた実害は器を返す再帰（写像）に出ていた。「並べるものの幅」が決まらないので
// sret の計画が立たず、`List` を返す写像だけが出せなかった——`String` は型名に要素が
// 入っている（`≅ List(Char)`）ので偶然通っていた。
check("器の実引数で要素型まで狭まる", entries("f : st ? st ' 0\nf [1 2 3]"), ["f : List -> Int"]);
// **丸ごと受ける形（`[~st]`）にも呼び出しサイトの型が届く。**
//
// `[c ~rest]` の分解は実引数1個を割るので位置と名前が1対1にならないが、`[~st]` は
// 渡された実引数**そのもの**を受けるので、裸の仮引数と同じく型を持つ。ここを一律
// 「分解だから位置が対応しない」と読んでいたため、`push : [~st] d ?` の `st` に型が
// 届かず、渡し方が「器か分からないので1本」になっていた——呼ぶ側は器（2本）で渡すので
// 幅が食い違う。**宣言を正しく書いた方が弱くなる**という逆転である。
// `.st` は仮引数を**書かれた形**で書き写すので、表示は `[st~]` のままである（何を受ける
// かは書き手が宣言している）。届いているかは返値と、Pass 4 が渡し方を決められるかで見る。
check("丸ごと受ける形も書かれた形で写す", entries("f : [~st] d ? d st~\nf [1 2] 9"), ["f : [st~] Int -> List(Int)"]);
check("文字列の実引数で狭まる", entries("f : s ? s ' 0\nf `abc`"), ["f : String -> Char"]);
// **スカラーだけで呼ばれるなら、本当に長さ1である**（`[5] ≅ 5`）。使い方が同じでも器だと
// 決めてはいけない——`f : n ? n ' 0` を `f 5` と呼ぶ形と構文が同じであり、違うのは表現
// （レジスタ1本か `{ptr, len}` か）だけである。器だと決めるのは実引数が食い違うときで、
// そこは `joinParamType` が既に器へ寄せる。
check("スカラーだけなら持ち上げない", entries("f : st ? st ' 0\nf 0"), ["f : Int -> Int"]);

// ---- `[~x]` は宣言なので、裸で書くより強い ----
//
// 器だと言いたいなら仮引数リストで言う。書けば要素の型まで決まる——分解の形が
// 「これは器で、これがその中身だ」と述べているからである（型はコードの影）。
//
// **仮引数が他にもあると器の型が落ちていた。** 分割代入の rest 名へは要素型しか書いて
// おらず、`[~ts]` 1つだけの形は別の経路が通るので偶然動いていた。結果、宣言した方が
// 裸で書くより弱いという逆転が起きていた——`f : a [~ts] ?` の `ts` は要素型を持ちながら
// 器の型が `null` だった。
check("[~ts] 単独", entries("f : [~ts] ? ts ' 0\nf [1 2 3]"), ["f : [ts~] -> Int"]);
check("[~ts] が他の仮引数と並ぶ", entries("f : a [~ts] ? ts ' a\nf 0 [1 2 3]"), ["f : Int [ts~] -> Int"]);
check("[~ts] が文字列を受ける", entries("f : a [~ts] ? ts ' a\nf 0 `abc`"), ["f : Int [ts~] -> Char"]);

// ---- 構造体は名前で分ける（`[key1 key2 ~it]`）----
//
// 名前と仮引数名が一致すれば順番に関わらず束縛される（function_guide.md「構造体
// メンバーの一致による自動バインディング」）。物理配置は名前でソートした正規順だが、
// 束縛は名前で結ぶので順序に依らない——スロットの型がそのまま束縛の型である。
{
	const look = (s, n) => { while (s) { const b = s.bindings instanceof Map ? s.bindings.get(n) : s.bindings[n]; if (b) return b; s = s.parent; } return null; };
	const SRC = "calc_diff : [foo bar ~obj] ? foo - bar\ncalc_diff [\n\tbar : 20\n\tfoo : 100\n]";
	const { nodes } = compile(SRC, { charset: "ascii" });
	const d = nodes.find((n) => n.name === "define" && String(n.left.value).includes("calc_diff"));
	check("名前で分けた型（foo）", (look(d.right.scope, "<foo>") || {}).atomType, "Int");
	check("名前で分けた型（bar）", (look(d.right.scope, "<bar>") || {}).atomType, "Int");
	// `~obj` は器そのもの。並びもここへ置く——Pass 4 の入口がそこから固定オフセットを引く。
	const rb = look(d.right.scope, "<obj>") || {};
	check("器そのものは Struct", rb.atomType, "Struct");
	check("並びを持つ", (rb.shape && rb.shape.slots || []).map((s) => `${s.name}@${s.offset}`), ["bar@0", "foo@8"]);
}

check("添字スタイルは器だと分かる", entries("hd : s ?\n\t(s ' 0) = `a` : __\n\t(s ' 0) (hd (s ' 1~))"), [
	"hd : Container -> List",
]);


// ---- 実引数の位置が仮引数の型を語る ----
//
// `h : y ? g y` の `y` は `g` が要求する型である。演算子から逆算するのと同じことを、
// 演算子の代わりに**呼び先のシグネチャ**でやっている——どちらも「その位置に置ける型は
// 何か」を読んでいるだけである。返値型と仮引数型は互いに依存するので同じ不動点で回る。
check("2番目の引数でも逆流する", entries("g : a b ? 0.0 + b\nh : y ? g 1 y"), [
	"g : Int Float -> Float",
	"h : Float -> Float",
]);
// 仮引数のデフォルト式も使用箇所である。デフォルトは**他の仮引数を使って書ける**ので、
// 本体だけを見ていると仮引数リストの中でしか使われない引数が `Atom` のまま残る。
check("デフォルト式の中の使用も拾う", entries("g : s ? 0.0 + s\nh :\n\tx\n\ty : g x\n?\n\ty"), [
	"g : Float -> Float",
	"h : Float Float -> Float",
]);
// 逆算した型はラムダのスコープへ書き戻す。書き戻さないと本体でその仮引数を読んだときに
// Pass 1a が置いた下限（`Atom`）しか見えず、返値型が実際より緩くなる。
check("デフォルトが式でも本体まで型が届く", entries("id : s ? s = \\a\nc :\n\traw\n\tb : id raw\n?\n\tb"), [
	"id : Char -> Char",
	"c : Char Char -> Char",
]);

// ---- 直和は平らにする ----
//
// arm の型が既に直和（再帰呼び出しの返値など）だと、それを1個の要素として数えてしまい、
// 周回のたびに `String | List | String | List | …` と伸び続ける。直和は冪等（`A | A = A`）
// であり結合的でもあるのだから、入れ子を保つ理由が無い。
check("入れ子の直和は展開して重複を落とす", entries("f : n ?\n\tn = 0 : \\s\n\tn = 1 : 1.0\n\tf (n - 1)"), [
	"f : Int -> Char | Float",
]);


// ---- 混在形のブラケット（`x [c ~r]`）も器の型が決まる ----
//
// 混在形はブラケットが1エントリへ畳まれ、内側の名前は `pattern` に入る。それらも本体で
// 使われる仮引数なので使用箇所からの逆算の対象であり、器の型を決める規則も全体ブラケットと同じ
// ——`[h ~t]` の `t` が残りの集合そのものだからである。
check("パターン内の要素から器が決まる", entries("f : col [h ~t] ?\n\th = col : 1\n\tf col t"), [
	"f : Scalar List -> Int",
]);

// ---- 相互再帰は束の底から上がる（null で底を壊さない） ----
//
// `null` は「まだ分からない」であって型ではない。束は `__`（底）から始めて単調に上がる
// 設計なので、途中の周回で読めなかったからといって底を壊してはいけない——相互再帰では
// 初回に必ず相手が未確定になるため、上書きすると二度と上がれなくなる。
check("相互再帰の返値が両方決まる", entries("a : n ?\n\tn = 0 : \\s\n\tb (n - 1)\nb : n ?\n\tn = 0 : \\t\n\ta (n - 1)"), [
	"a : Int -> Char",
	"b : Int -> Char",
]);
// rest だけのパターン（`[~xs]`）は**何の**集合かを決める手掛かりが無い——要素が無いので
// 「何が入っているか」を言えない。**だが器であることは言える**：ブラケットは器を受ける形の
// 宣言であり、呼ぶ側はスカラーを渡すときも形に合わせて持ち上げてから渡す。
//
// 仮引数は形のまま書く（`Container` は「器である」としか言っていないのに対し、形は「器で
// あり、こう分解する」まで言う——多くを言っている方を書く）。返値の側は名乗るものが型しか
// 無いので `Container` と出る。以前ここが `_`（分からない）だったせいで、呼び出しサイトから
// 流れてきたスカラーの型がそのまま残り、**型は 1 本と言うのに ABI は 2 本で運ぶ**という
// 食い違いになっていた（preprocess.sn の `push : [~st] d ? d st~`）。
check(
	"要素の無いパターンは形のまま、器であることは言う",
	entries("p : n [~xs] ?\n\tn > 0 : xs\n\tq n xs\nq : n [~ys] ?\n\tn > 0 : ys\n\tp (n - 1) ys"),
	["p : Int [xs~] -> Container", "q : Int [ys~] -> Container"]
);


// ---- 実プログラムで未解決が残らないこと ----
//
// n_queens.sn は混在形のブラケット（`col dist [h ~t]`）と相互再帰（place ↔ try_col）の
// 両方を含む。どちらか一方でも欠けると `_` が残るので、全体が解けることが両者の噛み合いの
// 証拠になる。
{
	const src = fs.readFileSync(path.join(__dirname, "..", "..", "..", "documents", "ja-jp", "guide", "examples", "n-queen", "n_queens.sn"), "utf8");
	const { nodes, env } = compile(src);
	const r = generateSignType(nodes, env, { scope: "ist" });
	check(`n_queens.sn に未解決が残らない（${r.entries} エントリ）`, r.unresolved, 0);
	check("solve は盤（List）を返す", r.text.includes("solve : Int -> List"), true);
}


// ---- 真理値の型は無い。真は `__` から導かれる（§2） ----
//
// Sign の真偽はどちらも値の型ではない。偽は `__`（零対象＝射が無いこと）、真は恒等射
// （何もしない射）である。恒等射は `__` と別物ではない——`__` は単位元なので単位律
// `x ⊗ __ ≅ x` が成り立ち、**`__` の積関手はそのまま恒等関手**だからである。
//
// 比較が値を返す（comparison.md「真なら LHS、偽なら `__`」）のも同じ設計の現れで、
// 真理値を作る代わりに値をそのまま通す。だから述語は**その値の型**になる。
check("値を返す述語は値の型になる", entries("is_digit : c ? \\0 <= c <= \\9"), ["is_digit : Char -> Char"]);
check("比較そのものも値を返す", entries("pos : x ? x > 0"), ["pos : Int -> Int"]);
// 恒等射を明示的に返す書き方だけが Layer 2 に名前を持たない。`.st` は `_` と書く
// ——裸の `_` は Sign 自身の恒等射記法なので（unit.md §378）、記号としてこれが正しい。
check("恒等射は `_` と書く", entries("id : !__"), ["id : _"]);
check("恒等射を返す述語も同じ", entries("t : x ?\n\tx = 0 : !__\n\t__"), ["t : Int -> _"]);
// **`Unit`（偽）と書いてはいけない。** `!__` は真であり、意味が逆になる。
check("`!__` は Unit ではない", entries("id : !__")[0].endsWith("Unit"), false);
// 非 Unit の否定は `__`（偽）である。
check("非 Unit の否定は Unit", entries("f : !5"), ["f : Unit"]);


// ---- `'`（添字・フィールドアクセス）は取り出したものの型を返す ----
//
// これまで `'` は左辺優先ルールへ落ちて**器の型をそのまま返して**いた——`[1 2 3] ' 0` が
// `Int` ではなく `List` になっていた。値は正しく `1` を返していたので、型だけが器のまま
// 取り残されていたことになる。Pass 4 は `base + i × sizeof(T)` を出すのに要素型 `T` を
// 必要とするので、ここは落としてはいけない情報である。
check("List(Int) の添字は Int", entries("l : [1 2 3]\np : l ' 0"), ["l : List(Int)", "p : Int"]);
check("List(Float) の添字は Float", entries("l : [1.0 2.0]\np : l ' 0"), ["l : List(Float)", "p : Float"]);
// `String ≅ List(Char)` なので、文字列の添字は要素型＝`Char` である（§2）——`List(Int)` の
// 添字が `Int` になるのと同じ引き方をする。**器の型を返してはいけない。** 返すと
// `is_digit : c ? \0 <= c <= \9` の `c` が呼び出しサイト（`s ' 0`）から `String` と
// 逆算され、レジスタ1本で比べる本体と `{ptr, len}` で受ける入口が食い違う。
check("String の添字は Char", entries("s : `abc`\np : s ' 0"), ["s : String", "p : Char"]);
// 添字が**部分列**を指す形（後置 `~` と範囲式）のときだけ、結果は器と同じ型になる。
check("部分列の添字は器の型", entries("l : [1 2 3]\np : l ' 1~"), ["l : List(Int)", "p : List(Int)"]);
// 名前付きスロットは名前で、連番スロットはリテラルの添字でそのスロットの型を引く
// ——スロットごとに型が違ってよいのが直積の意味だからである。
check("名前付きスロットはその名前の型", entries("d : [\n\tx : 1\n\ty : \\s\n]\np : d ' y").slice(1), ["p : Char"]);
check("連番スロットはその位置の型", entries("t : 1 , `a` , 2.5\np : t ' 2").slice(1), ["p : Float"]);


// ---- rest の要素型は「展開した先のスロット」が決める ----
//
// 後置 `~` は展開なので、`xs~` を呼び出しへ渡すとスロットに入るのは rest 自身ではなく
// **その要素**である。したがって呼び先のスロットの型がそのまま rest の要素型になる
// ——`sum : x ~xs ? x + (sum xs~)` の `xs` の要素は、展開先が `x` である以上 `x` と
// 同じ型でなければならない。実引数の位置から逆算するのと同じ規則を、要素の側で使っている。
check("再帰で自分へ展開する形", entries("sum : x ~xs ? x + (sum xs~)"), ["sum : Scalar Scalar~ -> Scalar"]);
check("別の関数へ展開しても同じ", entries("g : a ? 0.0 + a\nf : ~xs ? g xs~"), [
	"g : Float -> Float",
	"f : Float~ -> Float",
]);
check("1文字でも同じ", entries("g : c ? c = \\a\nf : ~cs ? g cs~"), ["g : Char -> Char", "f : Char~ -> Char"]);
// 多段でも周回のうちに伝わる（返値型・仮引数型と同じ不動点で回っている）。
check("多段の逆流", entries("g : a ? 0.0 + a\nh : ~ys ? g ys~\nf : ~xs ? h xs~"), [
	"g : Float -> Float",
	"h : Float~ -> Float",
	"f : Float~ -> Float",
]);
// 展開先は第1スロットとは限らない。
check("2番目のスロットへ展開", entries("g : a b ? 0.0 + b\nf : ~xs ? g 1 xs~"), [
	"g : Int Float -> Float",
	"f : Float~ -> Float",
]);
// 展開しなければ何も分からない。分からないことを「分かった」と書かないのが `.st` の原則。
check("証拠が無ければ `_~` のまま", entries("f : ~xs ? xs"), ["f : _~ -> _"]);

// **束の底は答えではない。** 返値型の不動点は `__`（零対象）から始めるが、それは再帰の枝が
// 初回に何も寄与しないようにするための種であって「何も返さない」という主張ではない。
// 一度も本体から型が読めなかった関数は「まだ分からない」のであり、種のまま報告すると
// `f : [x ~xs] ? xs` が `Unit` を返すと言い張りながら値はリストを返す——型と値が食い違う。
check("上がらなかった種は Unit と言わない", entries("f : [x ~xs] ? xs"), ["f : [x xs~] -> _"]);
// **呼び出しサイトが器を渡していれば、分解した先まで決まる。** `f [1 2 3]` は「`xs` は
// `List` である」と言っている——`[x ~xs]` は渡された器をその場で分解する形なので、
// 分解は同型の両側から読める。以前ここが `_` だったのは、ブラケットで受ける形（実引数
// 1個を分解する形）の呼び出しサイト観測を**丸ごと飛ばしていた**からで、「分からない」
// のではなく「見ていなかった」のである。証拠が無い上の行は今でも `_` のままになる。
// **要素型もそこまで届く。** `xs` は `f` の中では何の器か分からない——中身を決めているのは
// 実引数である。仮引数をそのまま返す位置を覚えておけば、呼ぶ側で実引数の要素型が読める。
// これが無いと、器を受け取ってそのまま返す関数の結果に添字が付けられなかった。
check("呼び出し側から決まる", entries("f : [x ~xs] ? xs\ng : f [1 2 3]"), ["f : [x xs~] -> List", "g : List(Int)"]);
// 本当に `__` を返すものは `Unit` のままである（種と区別が付いている）。
check("本当に __ を返すなら Unit", entries("f : x ? __"), ["f : Atom -> Unit"]);
// 再帰は種を必要とする。底から始めて基底ケースが型を決め、次の周回で再帰の枝へ伝わる。
check("再帰の返値型は従来通り決まる", entries("len : [c ~cs] ? cs & 1 + (len cs) | 1"), ["len : [c cs~] -> Int"]);

// **証拠は先に書いた方ではなく、具体的な方が勝つ。**
//
// 使用箇所は複数あり、証拠の強さが違う。`col > n` は「col は数である」としか言わない
// （相手も仮引数なので）が、`col + 1` は「col は Int である」と言う。先勝ちにすると
// 本体の**書いた順**で型が変わってしまう。族（`Atom` / `Scalar`）は証拠ではなく
// 証拠の不在なので、具体型が来たら譲る。
check("弱い証拠が先でも具体型が勝つ", entries("f : a b ?\n\ta > b : __\n\ta + 1"), ["f : Int Scalar -> Int"]);
check("順序を入れ替えても同じ", entries("f : a b ?\n\ta + 1 : __\n\ta > b"), ["f : Int Scalar -> Int"]);
// **族の中でだけ狭める。** `Scalar` に対する `Int` は「どの数か分かった」だが、
// `Scalar` に対する `List` は絞り込みではなく食い違いである——`List` は `Scalar` の
// 成員ではない（§4 の記法定義）。スカラーが1要素リストと同型なので、数を「盤」の
// スロットへ渡すことはできる。両方とも真だが、その仮引数自身の型は数である。
check("族の外から来た型では上書きしない", entries("g : x y ? y\nf : a b ?\n\ta > b : __\n\tg [1 2] a"), [
	"g : List Atom -> Atom",
	"f : Scalar Scalar -> Atom",
]);

// **前置 `@` / `#` はアドレスを要求する。** §3.5 の表が `@` を「`Address` → 参照先の圏を
// 継承」と定めており、参照を外せるのはアドレスだけである。だから `f : p ? @p 1` の `p` は
// `Address` だと書いてある——`x + 1` から `Int` を読むのと同じ、演算子からの逆算である。
//
// これは高階関数の受け口そのものである。Sign では関数を渡すときに `$is_digit` とアドレスを
// 取り、受け側は `@p` で呼ぶ（§2「高階関数の型解決は `$`/`@` による明示的な Lambda↔Atom
// 変換で足りる」）。仕組みは既にあったが、型がそれを書き写していなかった。
check("`@p` は p が Address だと語る", entries("f : p ? @p 1").map((l) => l.split("->")[0].trim()), ["f : Address"]);
check("複数引数でも位置を取り違えない", entries("f : p s ? @p s").map((l) => l.split("->")[0].trim()), [
	"f : Address Atom",
]);
// 中置 `#`（output、tier 4）は「アドレスにデータを入れる」ので**左辺**がアドレスである
// （前置 `#` は export 印なので別物——同じ記号でも位置で意味が違う）。
check("中置 `#`（書き込み）は左辺が Address", entries("f : p ? p # 1").map((l) => l.split("->")[0].trim()), ["f : Address"]);

// ---- 呼び出しサイトからの具体化（§5 Pass 1b の Layer 2 版） ----
//
// §7.1 の `Scalar` は「String を含まない Atom」という族であり、§1 は「呼び出しサイトで
// 具体化されるまでの暫定形」と明記している。Pass 1b は Layer 1（`Lambda` か `Atom` か）に
// ついてこれを既にやっていたが、Layer 2 についてはやっていなかった。
//
// **export されていない関数は、呼び出しサイトが全てである。** 外から呼ばれる可能性が
// 無いので、観測したサイトの型がその関数の型そのものになる。
check("呼び出しサイトが仮引数の型を決める", entries("f : n ? n\ng : f 8"), ["f : Int -> Int", "g : Int"]);
check("族に留まっている位置だけが埋まる", entries("f : a b ? a + b\ng : f 1 2.0"), [
	"f : Int Float -> Float",
	"g : Float",
]);
// 全サイトが同じ具体型で一致したときだけ狭める。食い違うなら族のままが正しい
// ——それは「まだ決まっていない」のではなく「複数の型で呼ばれている」ということであり、
// Pass 4 はサイトごとに別の実体を出す（コンパイル時特殊化）。
check("型の違うサイトが混ざれば族のまま", entries("f : a b ? a + b\nx : f 1 2\ny : f 1.5 2.5"), [
	"f : Scalar Scalar -> Scalar",
	"x : Scalar",
	"y : Scalar",
]);
// **export されているものはジェネリックのまま。** 外の呼び出しサイトは見えないので、
// 見えている分だけで決めつけてはいけない（compiler_pipeline.md §6.3 が呼び出しサイトの
// 列挙を export の性質として扱っているのと同じ線引きである）。
check("export されていれば狭めない", entries("#f : a b ? a + b\ng : f 1 2"), [
	"#f : Scalar Scalar -> Scalar",
	"g : Scalar",
]);
// 観測した型は識別子テーブルへ残す。狭めなかった場合でも、これが Pass 4 の出す実体の
// 一覧になる（export されていても記録はする）。
{
	const { env } = compile("#f : a b ? a + b\ng : f 1 2\nh : f 1.5 2.5");
	const b = env.bindings.get("<f>");
	check("観測した型は instances に残る", b && b.instances, [
		["Int", "Float"],
		["Int", "Float"],
	]);
}

// **偶然当たった型は、未解決より悪い。**
//
// 仮引数のように中身の見えない `Struct` はスロットへ分解できない。それでも連番添字の
// 経路は「分解できなかった器そのもの」を1個のスロットとして数えていたため、`p ' 0` が
// スロットの型ではなく**器の型**を返していた——`fst : p ? p ' 0` が `Struct -> Struct`
// になる。`p ' 1` は範囲外で `_` になるので、同じ書き方の 0 と 1 で答えの質が違っていた。
//
// 正しくは、**中身が見えないのは定義サイトだけ**である。呼ばれ方まで含めればスロットの
// 型は書いてあるので、呼び出しサイトから形（種別とスロットごとの型）を運べば解ける。
// 型名（`Struct`）だけでは足りない——スロットごとに型が違ってよいのが直積の意味なので、
// 必要なのは並びそのものである。
check("呼び出しサイトの形で添字が解ける", entries("f : p ? p ' 0\ng : f (1 , 2.5)"), [
	"f : Struct -> Int",
	"g : Int",
]);
check("スロットごとに違う型が出る", entries("f : p ? p ' 1\ng : f (1 , 2.5)"), [
	"f : Struct -> Float",
	"g : Float",
]);
check("名前付きスロットも名前で引ける", entries("f : p ? p ' y\ng : f [\n\tx : 1\n\ty : 2.5\n]"), [
	"f : {y} -> Float",
	"g : Float",
]);
// 関数の戻り値として渡されても形は届く——形は呼び出しサイトに**書いてある式**の先にある。
check("戻り値経由でも形が届く", entries("mk : a ? a , 2.5\nf : p ? p ' 1\ng : f (mk 1)"), [
	"mk : Int -> Struct(Int Float)",
	"f : Struct -> Float",
	"g : Float",
]);
// **形が食い違うサイトが混ざれば解けない。** それは「まだ分からない」のではなく
// 「複数の形で呼ばれている」ということであり、Pass 4 はサイトごとに別の実体を出す。
// 一方の形を選んで答えると、もう一方の呼び出しに対しては嘘になる。
check("形が違うサイトが混ざれば解けない", entries("f : p ? p ' 0\na : f (1 , 2)\nb : f (1.5 , 2.5)"), [
	"f : List -> _",
	// 呼び先の返値が未解決なら、適用の結果も未解決である。
	"a : _",
	"b : _",
]);

// **族は観測ではない。** 呼び出しサイトの実引数がまだ族なら、それは「まだ分かっていない」の
// 言い換えであって型の主張ではない。観測に数えると具体型と食い違い、「複数の型で呼ばれて
// いる」に見えてしまう。
//
// これが効くのは再帰である。自分自身を呼ぶとき、決めようとしている仮引数がそのまま
// 実引数として渡る——決めたいものを証拠として数える循環になる。
check("再帰の自己呼び出しが具体化を打ち消さない", entries("f : n ?\n\tn > 0 : f n\n\tn\ng : f 8"), [
	"f : Int -> Int",
	"g : Int",
]);

// **族が既に含んでいる枝は畳む。** §4 の記法定義では `Atom` は `Scalar | String` であり、
// `Scalar` は `Int | Address | Float | Vector` である。したがって `Atom | String` は `Atom`
// であって、`| String` は何も足していない。畳まないと「表現を決めるべき直和」が水増しされる
// ——Pass 4 から見れば枝が2つあるように見えるが、実際には1つの族でしかない。
check("Atom | String は Atom（String は Atom の成員）", entries("f : x y ?\n\ty : x\n\t`s`").map((l) => l.split("->")[1].trim()), ["Atom"]);
check("Scalar | Int は Scalar", entries("f : a b ?\n\ta > b : a + b\n\t1").map((l) => l.split("->")[1].trim()), [
	"Scalar",
]);
// 族と関係の無い枝は畳まない。`String` と `List` はどちらも他方を含まない。
check("含み合わない枝は残る（String と List は互いを含まない）", entries("f : x ?\n\tx : \\s\n\t[1 2 3]").map((l) => l.split("->")[1].trim()), ["Char | List"]);

// **分解は同型の両側から読める。** 既存の規則は「要素の型が分かれば器の型も決まる」という
// 向きしか持っていなかったので、器の側からしか情報が無い場合に要素が族のまま残っていた。
// `[h ~t]` は渡された集合をその場で分解するので、渡ってくるのが `List(Int)` なら `h` は Int。
check("器の要素型が分解した先へ届く", entries("f : [h ~t] ? h + 0\ng : f [1 2 3]"), [
	// 器の型が分かったので、形（`[h t~]`）ではなく型で書かれる——形は「まだ型が
	// 分かっていない」ときの記述である（下の paramTypeText の分岐）。
	"f : List(Int) -> Int",
	"g : Int",
]);
// 実引数の型は**それが書かれた場所**でしか引けない。器が何段も引数として渡り歩く形では、
// サイトごとにスコープを持ち回らないと連鎖が切れる。
check("何段渡り歩いても要素型が届く", entries("f : [h ~t] ? h + 0\ng : [~xs] ? f xs\nh : g [1 2 3]"), [
	"f : List(Int) -> Int",
	"g : List -> Int",
	"h : Int",
]);
check("中身が見えていればスロットの型が出る", entries("t : 1 , 2.5\na : t ' 0\nb : t ' 1"), [
	"t : Struct(Int Float)",
	"a : Int",
	"b : Float",
]);

// **片方が族なら、算術の結果も族である。** `Int + Scalar` を `Int` と答えてはいけない
// ——相手が Float なら昇格して Float になり、Address なら Address になる。具体型の側を
// そのまま答えにすると、分かっていないことを分かったと書くことになる（原理4）。
check("族が混ざれば結果も族", entries("f : a b c ? (a + 1) + b + c").map((l) => l.split("->")[1].trim()), [
	"Scalar",
]);


// レンジは有限でも無限でも「同じ型の要素が並ぶもの」であり、要素型を持つ（list_model.md §2.3）。
// 実体を持つかどうか（List か Iterator か）は項の数が決めるが、それは**器の違い**であって
// 要素型の有無ではない。Pass 4 は添字に対して要素1個ぶんの命令を出すので、ここが要る。
check("有限レンジは List(T)", entries("h : 1 ~ 5"), ["h : List(Int)"]);
check("無限ストリームは Iterator(T)", entries("a : 0 ~+ 1"), ["a : Iterator(Int)"]);
check("どちらの添字も要素型になる", entries("h : 1 ~ 5\na : 0 ~+ 1\ni : h ' 2\nj : a ' 3"), [
	"h : List(Int)",
	"a : Iterator(Int)",
	"i : Int",
	"j : Int",
]);
// stack_abi.md §3.3 のループカウンタ。開端レンジをデフォルト引数へ置くと、その関数は
// 「Iterator を受けて要素を返すもの」として型が付く——再帰を書かずにループが成立する形である。
check("開端レンジをデフォルトに持つ関数の型", entries("f :\n\tc : [0 ~+ 1]\n?\n\tc ' 3"), ["f : Iterator -> Int"]);
// レンジの端点も比較と同じ制約を持つ。§4 のシグネチャ
// `~ : (Point -> Point) -> Iterator -> (List | String)` が「両端は同じ点」と定めている
// 以上、片方が分かればもう片方も決まる——注釈を足したのではなく、演算子の定義を読んだだけ。
check("端点から仮引数の型が決まる", entries("mk : n ? [1 ~ n]"), ["mk : Int -> List(Int)"]);
check("適用の結果も要素型を運ぶ", entries("mk : n ? [1 ~ n]\ng : mk 5"), ["mk : Int -> List(Int)", "g : List(Int)"]);

// **形は受け取り方であって、型ではない。** `[acc~]` は「器を1つ受けてこう分解する」と
// しか言っておらず、**何の器かを言っていない**。ここを未解決に数えていなかったので、
// `.st` は仮引数の型が丸ごと決まっていない関数を「未解決 0」と報告していた——伏せずに
// 出すのが `.st` の目的なのだから、目的そのものを外していたことになる。
//
// 型が決まっていれば `List(Char)` のように書かれる（形へ落ちるのは決まらなかったとき
// だけ）ので、括りの形をしていること自体が「決まらなかった」の印である。
check("形しか書けなければ未解決", holes("f : [~s] ?\n	s ' 0\nf `abc`"), 1);
check("型が決まれば未解決でない", holes("f : n ? n + 1\nf 1"), 0);

// **仮引数の型を決めるのは呼ぶ側である**（type_system.md §5——呼び出しサイトで実引数の
// 具体的な型を用いて具体化する）。観測はできていたのに束縛へ書かれておらず、本体からの
// 推定（「器として使った」＝`Container`）だけが残っていた。蓄積子はそれで輪になる：
// `go (acc~ , x) …` の `acc` が `Container` → `acc~ , x` が「揃わない」→ `Struct` →
// その `Struct` が次の周回の観測に混ざる、と自分で自分を確認していた。
//
// **ただしスカラーの観測を器の仮引数へ書いてはいけない。** `bottom : 0` を `[~st]` へ
// 渡せるのは持ち上げ（原理8）が効くからであって、`st` が数だというわけではない
// ——書くと受け側が1本、呼ぶ側が2本で幅が食い違う。形は受け取り方を宣言している。
check(
	"器の仮引数は呼ぶ側から決まる",
	entries("go : [~acc] [~ts] i ?\n	i > 2 : acc\n	go (acc~ , (ts ' i)) ts (i + 1)\ngo [`z` , `w`] [`a`] 0").filter((l) => l.startsWith("go :")),
	// 返値が `Container`（器としか分からない）から `List` へ上がったのがその証拠である。
	// **`.st` の表示側にはまだ穴がある**——仮引数は本体の使われ方しか見ないので、束縛に
	// 載った具体型（`List` / 要素 `Char`）が出ずに形のままになる。そこは別件。
	["go : [acc~] [ts~] Int -> List"]
);
check("文字の端点なら String", entries("upto : c ? [\\a ~ c]"), ["upto : Char -> String"]);
console.log(`\n${passed}/${total} passed`);
process.exit(passed === total ? 0 : 1);
