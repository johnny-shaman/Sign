/**
 * **余積の「撒くか、1要素か」を、両側で同じ規則にしておく門。**
 *
 * 規則は 2026-09-10（7149efc）に決まっている——**どちら側でも、`~` を書けば撒く、
 * 書かなければ1要素**。そのとき解釈器が持っていた「左辺は常に撒く」を捨てた。
 * 当時 qemu は緑のままだったが、それは**差が出る入力を誰も書かなかったから**である
 * （数えた候補 24 か所のうち、実際に振る舞いが違うものは 0 件だった）。
 *
 * その入力が 2026-09-17 に見つかった:
 *
 *     f : l ? l 9   に [5 6 7] を渡すと   解釈器 2 / 機械 4
 *
 * 機械は古い規則で撒いていた。**診断は出ない。長さだけが違う。** 一番外に直接書いた
 * `||[5 6 7] 9||` も大域の `a : [5 6 7] 9` も機械はちゃんと断るので、**断る道は在るのに
 * 仮引数の道（sret）だけが黙って通っていた**。
 *
 * この門が見るのは3つ:
 *
 *   1. **一致**。期待値は書かない（`agree`）——仕様の答えは解釈器が持っているので、
 *      ここで二重に書くと片方だけ直る（[[project_sign_unit_law_criterion]] と同じ理由）。
 *   2. **断りの言い分**（`named`）。黙った誤答を断りに変えたのがこの直しの本体なので、
 *      「何が出せないのか」を診断が言っていることまで見る。数だけ見ていると、止まった
 *      場所が動いても気づかない。
 *   3. **バイトに収まらない値**。掃いたときの値（9）は 1 byte に収まるので、`String` へ
 *      数を並べる形は**偶然一致していた**。300 を入れると 44 が返る。
 *      オラクルが演算の副産物だと、こうして黙って空振りする（[[project_sign_parasitic_oracle]]）。
 *
 * ここは `qemu.test.js` と同じ問いを別の軸で立てているが、聞いていることが違う
 * ——あちらは「この構文が機械で動くか」、こちらは「**撒く／1要素**の判断が2つの実装で
 * 一致しているか、一致しないなら名指しで断っているか」である。だから走らせる形も
 * 掃いた表（左辺6 × 右辺3 × 印4 × 演算3）から採っていて、道具は小さいまま持つ。
 *
 * 実行: node test/coproduct_spread.test.js
 */
import peggy from "peggy";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { compile } from "../compile.js";
import { generateAsm } from "../pass4.js";
import { evaluate, newRuntimeEnv, UNIT, observe, isUnit } from "../interpreter.js";
import { runAsm, asInt, available, toolReport } from "../qemu_run.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const parser = peggy.generate(fs.readFileSync(path.join(__dirname, "..", "sign.pegjs"), "utf8"));

let passed = 0;
let total = 0;
let skipped = 0;

// **入っていないことと落ちることは別。** 走らせる検査だけ飛ばす——断りの言い分を見る側は
// コンパイルしか要らないので、ツールチェーンが無くても見られる。
const HW = available();
if (!HW) console.log(`実機は飛ばす（${toolReport()}）——断りの言い分だけ見る`);

const ASM = { target: "aarch64_qemu", charset: "ascii", layer: 1 };

// 解釈器の答え。観測境界を通した姿で見る。**`Char` は符号位置へ揃える**
// （`String ≅ List(0u)`——解釈器は読める姿の1文字を返すが、機械にあるのは数である）。
function interp(source) {
	const { nodes } = compile(source, { parse: parser.parse, charset: "ascii" });
	const env = newRuntimeEnv(null, "ascii");
	let r = UNIT;
	for (const node of nodes) r = evaluate(node, env);
	if (isUnit(r)) return "__";
	const o = observe(r);
	if (o === undefined || o === null) return "__";
	if (typeof o === "string" && [...o].length === 1) return String(o.codePointAt(0));
	return String(o);
}

// 機械の答え。`_sign_main` の x0 を符号付き64ビットで読む。
function machine(source) {
	const { nodes, env } = compile(source, { charset: "ascii" });
	const r = generateAsm(nodes, env, ASM);
	if (r.diagnostics.length) return "出せない：" + r.diagnostics[0].message;
	const v = asInt(runAsm(r.text)[0]);
	return v === null ? "__" : String(v);
}

/**
 * **まだ割れている形を、割れたまま覆う。**
 *
 * `corpus.js` が `n_queens.sn` の既知の1件を「除外せず記録して覆う」のと同じ作法である。
 * 除外すると**直ったことも隠れる**——直した日にこの検査が落ちて、書き換えるよう促す。
 * 期待値（どちらの答えが正しいか）は書かない。**割れていること**だけを記録する。
 */
function stillSplit(note, source) {
	if (!HW) {
		skipped++;
		return;
	}
	total++;
	let a, b;
	try { a = interp(source); } catch (e) { a = "解釈で例外：" + e.message; }
	try { b = machine(source); } catch (e) { b = "機械で例外：" + e.message; }
	// **両方が例外なら割れではない。** 綴りが構文で落ちているだけなので、
	// 言い分の接頭辞が違うぶんだけ a !== b になり、黙って通ってしまう。
	const broke = (x) => x.startsWith("解釈で例外：") || x.startsWith("機械で例外：");
	if (broke(a) || broke(b)) {
		console.log(`FAIL ${note.padEnd(40)} 綴りが落ちた：解釈=${a} / 機械=${b}`);
	} else if (a !== b) {
		passed++;
		console.log(`ok   ${note.padEnd(40)} 既知の割れ：解釈=${a} / 機械=${b}`);
	} else {
		console.log(`FAIL ${note.padEnd(40)} **直った** 両方 ${a}——この行を agree へ移すこと`);
	}
}

/** 同じソースを両方へ通し、答えが**一致すること**だけを見る。期待値は書かない。 */
function agree(note, source) {
	if (!HW) {
		skipped++;
		return;
	}
	total++;
	let a, b;
	try {
		a = interp(source);
	} catch (e) {
		a = "解釈で例外：" + e.message;
	}
	try {
		b = machine(source);
	} catch (e) {
		b = "機械で例外：" + e.message;
	}
	if (a === b) {
		passed++;
		console.log(`ok   ${note.padEnd(40)} ${a}`);
	} else {
		console.log(`FAIL ${note.padEnd(40)} 解釈=${a} / 機械=${b}`);
	}
}

/**
 * **断っていること**と、**その言い分**を見る。
 *
 * 断りが別の理由へ移ったら落ちる——「数は 1 のまま理由が入れ替わる」形を見逃さないため
 * である（`corpus.js` の頭にある、`em.fail` を1つ止めたら下の節が代わりに積まれた件と
 * 同じ）。ここは走らせない（コンパイルだけ）ので速い。
 */
function named(note, source, reason) {
	total++;
	let msg = "（診断が出なかった）";
	try {
		const { nodes, env } = compile(source, { charset: "ascii" });
		const r = generateAsm(nodes, env, ASM);
		if (r.diagnostics.length === 0) {
			// **ここは値を見ていない。** 走らせないので「断らないが値は合っている」と
			// 「断らないうえに誤答」を見分けられない。見分けるのは `agree` の側である。
			msg = "（診断が出なかった——値が合っているかはここでは見ていない）";
		} else if (!r.diagnostics[0].message.includes(reason)) {
			msg = "別の理由：" + r.diagnostics[0].message;
		} else {
			passed++;
			console.log(`ok   ${note.padEnd(40)} ${reason}`);
			return;
		}
	} catch (e) {
		msg = "例外：" + e.message;
	}
	console.log(`FAIL ${note.padEnd(40)} ${msg}`);
}

// 断りの言い分。**言い分ごとに1つの名前**にしておく（同じ文を検査に何度も書かない）。
const NEST = "は1要素だが、要素の幅が"; // 撒いていない器を、幅の足りないセルへ置こうとした
const MIX = "幅の違う要素は混ぜられません"; // 撒いた相手の要素の幅が、置き場と違う
const TEXT = "文字列に並べられるのは文字と文字列だけです"; // 数を綴りへ直す道が無い
const LIFT = "原理8 の表現の代金が未実装"; // スカラーを `{ptr, len}` へ持ち上げられない
const BOUND = "返す器の上界が出せなかった"; // sret の上界が言えない
const JOIN = "型の合流が撒いた側を開けていない"; // 撒く相手の要素型が器そのものになっている

// 掃いた表と同じ雛形。`g` は大域の器、`l`/`m` は仮引数、観測は4通り。
const SRC = (body, pre = null, obs = "||f [5 6 7] [1 2]||") =>
	"g : [5 6 7]\n" + (pre ? pre + "\n" : "") + `f : l m ? ${body}\n` + obs;
const OBS = [
	["||…||", "||f [5 6 7] [1 2]||"],
	["' 0", "(f [5 6 7] [1 2]) ' 0"],
	["' 1", "(f [5 6 7] [1 2]) ' 1"],
	["' 3", "(f [5 6 7] [1 2]) ' 3"],
];

// ---------------------------------------------------------------------------
// §1 報告された的——`l 9` / `9 l`。4観測とも黙って違う値を返していた。
// ---------------------------------------------------------------------------
console.log("--- §1 報告された的（解釈器 2 / 機械 4 だった形） ---");
for (const obs of ["||f [5 6 7]||", "(f [5 6 7]) ' 0", "(f [5 6 7]) ' 1", "(f [5 6 7]) ' 3"]) {
	named(`l 9 ${obs.replace("f [5 6 7]", "…")}`, `f : l ? l 9\n${obs}`, NEST);
	named(`9 l ${obs.replace("f [5 6 7]", "…")}`, `f : l ? 9 l\n${obs}`, NEST);
}
// 対照——同じ左辺でも `~` を書けば通る。ここが通らなくなったら直しすぎている。
for (const obs of ["||f [5 6 7]||", "(f [5 6 7]) ' 0", "(f [5 6 7]) ' 3"]) agree(`l~ 9 ${obs.replace("f [5 6 7]", "…")}`, `f : l ? l~ 9\n${obs}`);
// 一番外と大域は前から断っていた。**断る道が在るのに仮引数の道だけ通っていた**のが件の骨格
// なので、そちらが動いていないことも留める。
named("一番外に直接書いた `[5 6 7] 9`", "||[5 6 7] 9||", "器の構築はまだ出せません");
named("大域に束ねた `a : [5 6 7] 9`", "a : [5 6 7] 9\n||a||", "器の構築はまだ出せません");

// ---------------------------------------------------------------------------
// §2 掃いた表（768 観測）で黙って割れていた **26 形を1つ残らず**。
//     **26 形すべて**が「黙って別の値」から**名指しの断り**へ変わった（下の 26 行は全部
//     `named()` を通る）。
// ---------------------------------------------------------------------------
console.log("--- §2 黙って割れていた 26 形（全部） ---");
const BROKEN = [
	// 撒けと書いていないのに撒いていた（要素の幅が 16 未満なので器を1つ置けない）
	["仮引数の器 / スカラー / 無し / 空白", "l 9", null, NEST],
	["仮引数の器 / スカラー / 無し / 名前越し", "l n", "n : 9", NEST],
	["仮引数の器 / スカラー / 右~ / 空白", "l 9~", null, NEST],
	["仮引数の器 / スカラー / 右~ / 名前越し", "l n", "n : 9~", NEST],
	["組立中の余積 / 仮引数 / 無し / 空白", "1 2 m", null, NEST],
	["スカラー / 仮引数 / 無し / 空白", "5 m", null, NEST],
	["スカラー / 仮引数 / 左~ / 空白", "5~ m", null, NEST],
	// 撒いた相手の要素の幅が、置き場（`{ptr, len}`）と違う——`' 0` が生の番地
	// （1090518944）を返していた形である。名前の要素型は注釈に無いので束縛から引く。
	["仮引数の器 / 仮引数 / 右~ / カンマ", "l , m~", null, MIX],
	["仮引数の器 / 仮引数 / 両~ / カンマ", "l~ , m~", null, MIX],
	["大域の器 / 仮引数 / 右~ / カンマ", "g , m~", null, MIX],
	["字面の器 / 仮引数 / 右~ / カンマ", "[5 6 7] , m~", null, MIX],
	["字面の器 / 仮引数 / 両~ / カンマ", "[5 6 7]~ , m~", null, MIX],
	["組立中の余積 / 仮引数 / 両~ / カンマ", "(1 2)~ , m~", null, MIX],
	["文字列 / 仮引数 / 右~ / カンマ", "`abc` , m~", null, MIX],
	["文字列 / 仮引数 / 両~ / カンマ", "`abc`~ , m~", null, MIX],
	// 束縛にも要素型が無いとき。**この器の要素型が撒く相手の型そのもの**になっているのは、
	// 型の合流が撒いた側を開けずに「器を要素と数えた」ということである。
	["大域の器 / 仮引数 / 両~ / カンマ", "g~ , m~", null, JOIN],
	// 積（`,`）の左は組み立て中の器ではない——`1 2 , 9~` は `[[1,2], 9]` の長さ2である。
	// 機械は左を開いて長さ3を返していた（`walkParts` が左右とも無条件に開いていた）。
	["組立中の余積 / スカラー / 右~ / カンマ", "1 2 , 9~", null, LIFT],
	// 文字列に数を並べる——解釈器は綴りへ直す（`'9'` = 57）が、機械は値のバイトを書いていた
	["文字列 / スカラー / 無し / 空白", "`abc` 9", null, TEXT],
	["文字列 / スカラー / 無し / 名前越し", "`abc` n", "n : 9", TEXT],
	["文字列 / スカラー / 右~ / 空白", "`abc` 9~", null, TEXT],
	["文字列 / スカラー / 右~ / 名前越し", "`abc` n", "n : 9~", TEXT],
	["文字列 / 仮引数 / 無し / 空白", "`abc` m", null, TEXT],
	["文字列 / 仮引数 / 左~ / 空白", "`abc`~ m", null, TEXT],
	["文字列 / 仮引数 / 右~ / 空白", "`abc` m~", null, TEXT],
	// ブラケットは「これは器である」と宣言している。`String` の μ が強制でも、そこは剥がさない
	["文字列 / 器 / 無し / 空白", "`abc` [1 2]", null, BOUND],
	["文字列 / 器 / 左~ / 空白", "`abc`~ [1 2]", null, BOUND],
];
for (const [name, body, pre, reason] of BROKEN) {
	for (const [label, obs] of OBS) named(`${body.padEnd(14)} ${label.padEnd(5)} ${name}`, SRC(body, pre, obs), reason);
}
{
	total++;
	// **数も見る。** 形を1つ落としても言い分は揃ったままなので、数が落ちるのを見張る。
	if (BROKEN.length === 26) {
		passed++;
		console.log("ok   掃いた表の 26 形が揃っている");
	} else console.log(`FAIL 掃いた表の 26 形が揃っていない（${BROKEN.length} 形）`);
}

// ---------------------------------------------------------------------------
// §3 対照——掃いた表で一致していた形は、一致したまま。
//     断りを広げすぎると、ここが先に落ちる。
// ---------------------------------------------------------------------------
console.log("--- §3 一致していた形は一致したまま ---");
for (const body of ["l~ 9", "l~ 9~", "l~ , 9", "5 9", "5 9~", "5~ 9", "5~ 9~", "5 m~", "5~ m~", "5 , 9", "5 , m~", "5~ , m~", "1 2 9", "1 2 9~", "1 2 m~"])
	for (const [label, obs] of OBS) agree(`${body.padEnd(10)} ${label}`, SRC(body, null, obs));
for (const pre of ["n : 9", "n : 9~"])
	for (const body of ["l~ n", "5 n", "5~ n", "1 2 n"]) agree(`${body}（${pre}）`, SRC(body, pre));

// ---------------------------------------------------------------------------
// §4 掃いたときの値では見えなかったぶん。
//
//     `` `abc`~ 9 `` は4観測とも一致していた——9 が 1 byte に収まるからである。
//     300 を入れると機械は 44（300 & 0xff）を返していた。**測り方が演算の副産物だと、
//     その演算を直したとき検査が黙って空振りする。**
// ---------------------------------------------------------------------------
console.log("--- §4 バイトに収まらない値（掃いた表のオラクルの盲点） ---");
for (const body of ["`abc`~ 300", "`abc` 300", "`abc`~ m~", "`abc`~ 300~"])
	named(`${body}（9 なら偶然合っていた）`, SRC(body, null, "(f [5 6 7] [300 400]) ' 3"), TEXT);
// 器の側は 300 でも通る（1 byte へ切り落としていないこと）。
agree("l~ 300 の ' 3", "f : l ? l~ 300\n(f [5 6 7]) ' 3");
agree("l~ 300 の長さ", "f : l ? l~ 300\n||f [5 6 7]||");

// ---------------------------------------------------------------------------
// §5 要素が `{ptr, len}` で運ばれる器（`List(String)`）の道は塞いでいない。
//     lexer.sn が乗っているのはここなので、閉めすぎたら自己ホストが止まる。
// ---------------------------------------------------------------------------
console.log("--- §5 List(String) の道は開いたまま ---");
agree("[a , b] の長さ", "f : a b ? [a , b]\n||f `ab` `cd`||");
agree("[a , b] の要素を辿る", "f : a b ? [a , b]\n||(f `ab` `cd`) ' 1~||");
agree("文字を綴りの前へ", "f : c s ? c s\n||f `x` `abc`||");
agree("綴りを綴りへ", "f : s ? `x` s\n(f `abc`) ' 1");
agree("綴りの連結の長さ", "f : s ? `x` s\n||f `abc`||");
// **閉めすぎの見張り。** 撒く相手の要素型が書いていないこと自体は悪くない——仮引数の
// `[~a]` は中身が見えないからである。ここを「分からないなら断る」にした版は、この3本と
// 自己ホストが使う蓄積子（`qemu.test.js` の「蓄積子：長さ」）を丸ごと殺した。
agree("撒いた器を左に置いても", "f : [~a] x ? a~ , x\n||f [`1` , `2`] `Z`||");
agree("右に撒いても同じ長さ", "f : [~a] x ? x , a~\n||f [`1` , `2`] `Z`||");
agree("呼び先が __ を返す（余積の単位元）", "h : x ? __\ng : s ? `<` (h (s ' 0)) `>`\n||g `ab`||");


// ---------------------------------------------------------------------------
// §6 **この直しが塞いでいない割れ**（実測、2026-09-17）。
//
// 幅の照合は `w === 16`（要素を参照で運ぶ器）の側にしか立てていない。だから
// `l~ , m~` は断るのに、**間にスカラーを1つ置いただけの `l~ 9 m~` は素通りする**。
// 「断る道が在るのに、別の道だけ黙って通る」——この直しが塞いだのとまったく同じ骨格が
// 1つ残っている。両側に幅の門を立てると `Int`/`Char` の混在まで全部断りになるので、
// そちらは**型の合流**（`pass3.js` の余積の要素型）の話として残した。
//
// 直した日はここが落ちる。落ちたら `agree` へ移すこと。
// ---------------------------------------------------------------------------
console.log("--- §6 まだ割れている（既知） ---");
const MIXED = "f : l m ? l~ 9 m~\n";
stillSplit("幅の違う器をスカラー越しに撒く：長さ", MIXED + "||(f [1 2] [`aa` , `bb`]) ' 4||");
stillSplit("幅の違う器をスカラー越しに撒く：中身", MIXED + "(f [1 2] [`aa` , `bb`]) ' 4 ' 0");
stillSplit("向きを変えても同じ", "f : l m ? m~ 9 l~\n||(f [1 2] [`aa` , `bb`]) ' 0||");
// 対照：幅が揃っていればスカラー越しでも通る。カンマに替えれば新しい門が働く。
agree("幅が揃っていればスカラー越しでも一致", MIXED + "||f [1 2] [3 4]||");
named("カンマなら幅の違いを断る", "f : l m ? l~ , m~\n||f [1 2] [`aa` , `bb`]||", "幅の違う要素は混ぜられません");

// **段の禁止が新しい門より先に立つこと。** 層が足りないのは設計上の結論であって「まだ」では
// ないので、言い分は**直す当ての有る方**（段を上げろ）でなければならない。
named("層1 の Float は段の言い分で断る", "f : s ? s 1.5\n||f `abc`||", "layer: 1 では Float を使えません");

if (skipped) console.log(`（実機が要る ${skipped} 件は飛ばした）`);
console.log(`\n${passed}/${total} passed`);
process.exit(passed === total ? 0 : 1);
