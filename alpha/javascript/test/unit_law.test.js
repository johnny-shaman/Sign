/**
 * **単位律で検査する。期待値は書かない。**
 *
 * これまでの検査は「インタプリタと実機が一致するか」で見ていた（`qemu.test.js`）。
 * それは強い軸だが、**両方が同じように間違っていると通ってしまう**——実際、UTF-32 の
 * 文字数は解釈器の側が壊れていて（JS の UTF-16 サロゲートが漏れる）、実機のほうが
 * 正しかった。オラクルが壊れているとき、一致は何も保証しない。
 *
 * ここは別の軸を足す。**片側だけで確かめられる法則**、すなわち単位律である。
 *
 *   どの演算 op についても   a op 単位元 == a
 *   どの分解についても       ||残り|| >= 0
 *   どの束縛についても       効果は1回
 *   どの仮引数の形でも       f __ == __     （完全性公理＝ε）
 *
 * 期待値（`7 + __ は 7`）を書くのではなく、**法則（`a + __ は a`）**を書く。だから
 * 解釈器と実機のそれぞれについて独立に成否が出るし、両方が同じ間違いをしても通らない。
 *
 * **なぜ単位律なのか。** `__` は双代数の単位元として振舞うことを要請されている
 * （`unit.md`）。単位元は演算の不動点であり、**演算を演算たらしめているものが単位律**
 * である。そして単位元の「側」が演算の役を決めている：
 *
 *   両側に単位元がある   `+ - * / % ^ << >> ; ,`   作る
 *   左だけ               `&`（単位元は `!__`）      選ぶ
 *   左だけ               `|`（単位元は `__`）       落とす
 *   右だけ               `'`（単位元は `0`）        観測する
 *   無い（`__` は零元）  `< =`                      判定する
 *
 * 実際、この軸で見つかった不具合は「別々の4件」ではなく **1つの規準の4箇所**だった。
 *
 * 実行: node test/unit_law.test.js
 */
import peggy from "peggy";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { compile } from "../compile.js";
import { generateAsm } from "../pass4.js";
import { evaluate, newRuntimeEnv, UNIT, observe, isUnit } from "../interpreter.js";
import { runAsm, asInt, available, toolReport } from "../qemu_run.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const parser = peggy.generate(fs.readFileSync(path.join(__dirname, "..", "sign.pegjs"), "utf8"));

let passed = 0;
let total = 0;

const HAS_QEMU = available();
if (!HAS_QEMU) console.log(`実機側は飛ばす（${toolReport()}）——解釈器側の法則だけ見る`);

/** 解釈器で走らせて、見える姿の文字列を返す。`qemu.test.js` の `interp` と同じ揃え方。 */
function interp(source, charset = "ascii") {
	const { nodes } = compile(source, { parse: parser.parse, charset });
	const env = newRuntimeEnv(null, charset);
	let r = UNIT;
	for (const node of nodes) r = evaluate(node, env);
	if (isUnit(r)) return "__";
	const o = observe(r);
	if (o === undefined || o === null) return "__";
	if (typeof o === "string" && [...o].length === 1) return String(o.codePointAt(0));
	if (o && typeof o === "object" && o.__identity__) return "0";
	return String(o);
}

/** 機械で走らせる。出せないものは `拒否` を返す——**出せないことと間違うことは別**である。 */
function machine(source, charset = "ascii", layer = 1) {
	const { nodes, env } = compile(source, { charset });
	const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset, layer });
	if (r.diagnostics.length) return "拒否";
	const v = asInt(runAsm(r.text)[0]);
	return v === null ? "__" : String(v);
}

/**
 * **法則をひとつ検査する。** 左辺の式と右辺の式が同じ値になることだけを見る。
 * 期待値は書かない——`law("a + __ == a", "7 + __", "7")` ではなく、両方を走らせて
 * 突き合わせる。解釈器と実機は**別々に**判定する（片方が拒否ならその側は数えない）。
 */
function law(note, lhs, rhs, opts = {}) {
	const { charset = "ascii", wrap = (e) => e } = opts;
	const sides = [["解釈", (s) => interp(wrap(s), charset)]];
	if (HAS_QEMU) sides.push(["機械", (s) => machine(wrap(s), charset)]);
	for (const [who, run] of sides) {
		let a, b;
		try { a = run(lhs); } catch (e) { a = "例外：" + e.message; }
		try { b = run(rhs); } catch (e) { b = "例外：" + e.message; }
		// **出せないことと間違うことは別である。** 片方でも「拒否」なら、その側は法則に
		// ついて何も言っていない（「まだ」と言えている）ので数えない。ここを失敗に数えると、
		// 実装の穴と設計の誤りが混ざって、直したいものが見えなくなる。
		if (a === "拒否" || b === "拒否") continue;
		total++;
		if (a === b) {
			passed++;
			console.log(`ok   ${who} ${note.padEnd(46)} ${a}`);
		} else {
			console.log(`FAIL ${who} ${note.padEnd(46)} ${lhs} → ${a} / ${rhs} → ${b}`);
		}
	}
}

// ---------------------------------------------------------------------------
// 1. 両側単位元：作る演算は `__` を不動点に持つ
// ---------------------------------------------------------------------------
// `a op __ == a` と `__ op a == a` の両方。**引き算や除算で向きが答えを変えない**のは
// 一見おかしいが、これは爆発律の代償として意図的にそうなっている（`operator_table.md`）
// ——単位元がひとつしかない以上、どの演算もそれを不動点にするしかない。
console.log("--- 1. 両側単位元（作る演算）---");
for (const op of ["+", "-", "*", "/", "%", "^", "<<", ">>", ";", ","]) {
	law(`a ${op} __ == a`, `7 ${op} __`, "7");
	law(`__ ${op} a == a`, `__ ${op} 7`, "7");
}

// ---------------------------------------------------------------------------
// 2. 片側単位元：選ぶ・落とす・観測する
// ---------------------------------------------------------------------------
// 単位元の「側」が演算の役を決めている。`&` は左が真なら右を返す**選択**なので、
// 左にしか単位元を持てない（`0 & a == a` だが `a & 0 == 0`）。`'` は**観測**なので
// 右にしか持てない（`a ' 0 == a`——1要素の器の 0 番目は自分自身、`[x] ≅ x`）。
console.log("\n--- 2. 片側単位元（選ぶ・落とす・観測する）---");
law("!__ & a == a（左単位元は真）", "!__ & 7", "7");

// ---- 密着演算子は零対象を動かさない ----
//
// **$__ = @__ = ~__ = __ が理想形である。** どれも射なので完全性公理（`f __ = __`）に
// 従う——例外を立てる必要が無い。型は Unit / Address / Raw / List と違うが、それは
// `__` が**あらゆる型に居る**（零対象は初対象かつ終対象）というだけで、値は1つである。
//
// **`__` かどうかは `=` では訊けない。** `=` も射なので `__ = __` は `__`（偽）になる。
// 訊く口は `!` ひとつで、`!x` が恒等射になるのは x が `__` のときだけである（☯）。
// だから法則は `!` の側で書く。
//
// ここは今まで `!__` しか見ておらず、$ / @ / ~ については**何も書かれていなかった**。
// 書かれていない法則は、壊れても気づけない。
law("!($__) == !__（アドレス化は零対象を動かさない）", "!($__)", "!__");
law("!(@__) == !__（入力も同じ）", "!(@__)", "!__");
law("!(~__) == !__（持ち上げも同じ）", "!(~__)", "!__");
law("!(__~) == !__（展開も同じ）", "!(__~)", "!__");
law("||$__|| == ||__||", "||$__||", "||__||");
law("||@__|| == ||__||", "||@__||", "||__||");
law("||~__|| == ||__||", "||~__||", "||__||");
// `=` は射なので、`__` を渡せば `__` が返る。「等しくない」ではなく「射に零対象を渡した」。
law("__ == __ は __（= も射である）", "__ = __", "__");
law("(~__) = __ も __（同上）", "(~__) = __", "__");
law("0 & a == a（0 は真）", "0 & 7", "7");
law("__ | a == a（左単位元は __）", "__ | 7", "7");
law("a ' 0 == a（右単位元は 0）", "7 ' 0", "7");
law("[a] ' 0 == a（1要素の器は無い）", "[7] ' 0", "7");
law("a ~ == a（μ∘η = id）", "7~", "7");
// **1要素を撒けばそれ自身である**（`[x] ≅ x`）。後置 `~` は値へ「撒く印」を付けるが、
// 印が意味を持つのは器を組む場所と引数の位置であって、算術は器を組まない。
// 解釈器が印を算術へ漏らしていて `n~ + 1` が `__` になっていた——機械は 0 命令で素通しして
// 3 を返すので、**診断ゼロで答えが割れていた**。法則で書けば片側だけ壊れても落ちる。
for (const op of ["+", "-", "*"]) {
	law(`n~ ${op} 3 == n ${op} 3`, `f : n ? n~ ${op} 3\nf 2`, `f : n ? n ${op} 3\nf 2`);
	law(`3 ${op} n~ == 3 ${op} n`, `f : n ? 3 ${op} n~\nf 2`, `f : n ? 3 ${op} n\nf 2`);
}

// ---------------------------------------------------------------------------
// 3. 不動点はちょうど2つで、`!` が対合である
// ---------------------------------------------------------------------------
// `__`（零）と `!__`（恒等射）。`!` はこの2つを入れ替えるので、2回かけると戻る。
console.log("\n--- 3. 不動点は2つ、`!` は対合 ---");
law("!!__ == __（対合）", "!!__", "__");
law("!(!__) == __（同じことを綴り違いで）", "!(!__)", "__");
// **無の個数は 0 である。** `||[]||` が 0 なのは器の定義から決まり、`[] = __`（unit.md）は
// 同一なので `||__||` も 0 でなければならない——**同型から降りてくる**。数え上げは器から
// Int への全域の射で、始対象から出る射は一意、その行き先が 0 である。
//
// ここは 0 → `__` → 0 と往復している。最初の 0 は実装の振舞いを写しただけで法則では
// なかったが、`__` にしたのも行き過ぎだった——捏造になるのは**逆向き**（0 を見て「器
// だった」と言うこと）で、順向きに数えるのは全域の射である。絶対値が器も数えていた
// あいだは役割が混ざっていて、そこが見えなかった。
law("||__|| == 0（無の個数は 0）", "||__||", "0");

// ---------------------------------------------------------------------------
// 4. ε（完全性公理）はどの仮引数の形でも発火する
// ---------------------------------------------------------------------------
// **`f __ == __` は仮引数の綴りに依存しない。** ここが破れると、本体が走ってはいけない
// ときに走る。実際 `[~a]` だけが実機で素通りしていた（呼ぶ側が `__` を長さ1の器へ
// 持ち上げ、受ける側は `len = 0` でしか見ていなかった——`__ = []` を2箇所で決めていた）。
//
// 本体は `99` のような**器を触らない定数**にする。値が返ってきたら、それは本体が
// 走った証拠そのものである。
console.log("\n--- 4. ε（完全性公理）はどの仮引数の形でも発火する ---");
for (const shape of ["x", "[~a]", "[a ~b]", "[h ~t]", "[a b ~c]", "[~a b]", "[a]"]) {
	law(`f : ${shape} ? 99 に __ → __`, `f : ${shape} ? 99\nf __`, "__");
}
law("分解した残りが尽きたら次の呼び出しも崩れる", "f : [h ~t] ? t & (f t) | 0\nf [1]", "0");

// ---------------------------------------------------------------------------
// 5. 長さの単位律：`||残り|| >= 0`
// ---------------------------------------------------------------------------
// 長さは自然数である。**0 が下限**であり、それが `__`（空の器）である。頭を器より
// 多く取っても負にはならない——`unit.md` が「`len = 0` が `__`」と定めている以上、
// 負の長さは表現できる値ではない。
//
// 切り出し（`' i~`）の側は `csel …, xzr, pl` で頭打ちにしている。分解（`[a b ~c]`）の
// 側にも同じ規準が要る——**同じ事実を2箇所で別々に決めない**。
console.log("\n--- 5. 長さの単位律（||残り|| >= 0）---");
for (const [shape, arg] of [
	["[a ~b]", "`x`"], ["[a b ~c]", "`x`"], ["[a b c ~d]", "`x`"], ["[a b c ~d]", "`xy`"],
	["[a ~b]", "[1]"], ["[a b ~c]", "[1]"], ["[a b c ~d]", "[1 2]"],
]) {
	// 「0 以上」を、Sign の中で `||c|| < 0` が偽（`__`）になることとして書く。
	const rest = shape.match(/~(\w+)/)[1];
	law(`f : ${shape} の ||${rest}|| は負にならない  ${arg}`,
		`f : ${shape} ? ||${rest}|| < 0\nf ${arg}`, "__");
}
// 尽きた残りは `len = 0` の器である。0 個の器の要素数は 0——数えられないのではない。
law("尽きた残りの個数は 0", "f : [a ~b] ? ||b||\nf `x`", "0");

// ---------------------------------------------------------------------------
// 除法の等式 — `/` と `%` は一つの割り目の二つの読み方である
// ---------------------------------------------------------------------------
// `/` は群の丈、`%` は最後の群のはみ出し。だから `a = (a/b)*b + a%b` が成り立つ
// （type_system.md §3.2）。**期待値を書かない**——値ではなく等式が閉じることを見る。
//
// 以前 `/` は四捨五入で `%` は切り捨ての剰余だったので、この等式は破れていた
// （`5/2 = 3` なら `3×2 + 1 = 7 ≠ 5`）。両方が実装されていながら、揃っているかを
// 見る検査が1本も無かった。**補正命令が要ることが、規則の誤りの合図だった。**
console.log("\n--- 除法の等式 a = (a/b)*b + a%b ---");
for (const [a, b] of [[5, 2], [7, 2], [1, 2], [4, 3], [5, 3], [9, 4], [10, 3], [0 - 5, 2], [0 - 7, 3], [6, 3]]) {
	law(`${a} = (${a}/${b})*${b} + ${a}%${b}`, `${a} / ${b} * ${b} + (${a} % ${b})`, String(a));
}

// ---------------------------------------------------------------------------
// 割り目は器でも同じ — 丈が商、余りは最後の群
// ---------------------------------------------------------------------------
// スカラーは丈を返し、器はその丈で切る。群の数は r、丈は要素数を r で割った商である。
// 丈が 0（`r` が要素数より大きい）なら空の群は余積の単位元として消え、元の器が残る。
console.log("\n--- 割り目は器でも同じ ---");
law("群の数は r", "||[1 2 3 4] / 3||", "3");
law("先頭の群の丈は商", "||([1 2 3 4] / 3) ' 0||", "||[1 2 3 4]|| / 3");
law("丈 0 なら分かれない", "||[1 2] / 5||", "||[1 2]||");
law("群が 0 個なら作れない", "[1 2 3 4] / 0", "__");

law("尽きた残りは __ そのもの", "f : [a ~b] ? b & 1 | 0\nf `x`", "0");

// ---------------------------------------------------------------------------
// 6. 範囲外の頭スロットは `__`
// ---------------------------------------------------------------------------
// 器が頭の数より短いとき、足りないスロットは `__` である——**器の外を読んではいけない**。
// 読んでしまうと隣の値や番地がそのまま値として出てくる（実際 `f : [a b c ~d] ? d ' 0`
// が RAM の番地を返していた）。
console.log("\n--- 6. 範囲外の頭スロットは __ ---");
law("[a b c ~d] の c は器の外  `xy`", "f : [a b c ~d] ? c\nf `xy`", "__");
law("[a b c ~d] の c は器の外  [7 8]", "f : [a b c ~d] ? c\nf [7 8]", "__");
law("[a b ~c] の b は器の外    `x`", "f : [a b ~c] ? b\nf `x`", "__");
// **範囲外を足すと 1 になるのが正しい。** 範囲外は `__` で、`__` は加法の単位元なので
// `__ + 1 == 1` である（節1で検査している法則そのもの）。ここを `__` だと書きかけたが、
// それは単位律と矛盾する——`__` は零元ではなく単位元である。両方を同時に要求できない。
law("範囲外は単位元として振舞う（__ + 1 == 1）", "f : [a b c ~d] ? c + 1\nf [7 8]", "1");

// ---------------------------------------------------------------------------
// 7. 効果の単位律：束縛は効果を1回だけ走らせる
// ---------------------------------------------------------------------------
// モナドの左単位則 `return a >>= f ≡ f a` は、**効果がちょうど1回**であることを要求する。
// `名前 : @p` は bind なので、`名前` を何回使っても読みは1回でなければならない。
// 使うたびに読むなら、それは bind ではなく代入（call-by-name）である。
//
// これは値では見えない（同じ番地を読めば同じ値が返る）ので、**出た命令を数える**。
console.log("\n--- 7. 効果の単位律（束縛は効果を1回）---");
function effectReads(source) {
	const { nodes, env } = compile(source, { charset: "ascii" });
	const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset: "ascii", layer: 1 });
	if (r.diagnostics.length) return null;
	// **何が効果かを正しく数える。** フレーム（`[x29, #..]`）からの読み戻しは効果ではない。
	// 束縛の置き場所（`adrp .Lbind_… / add … :lo12: / ldr`）を辿る読みも効果ではない
	// ——それは1回だけ観測した値を読み直しているだけである。ここを数えてしまうと、
	// **直したものが直っていないように見える**。
	// そして `bl` も数える。効果は関数の向こうに隠れうるので、呼び出し回数が増えれば
	// 効果も増えている（`rd : q ? @q` / `a : rd p` がその形）。
	const lines = r.text.split("\n").map((l) => l.trim());
	let n = 0;
	lines.forEach((l, i) => {
		if (/^bl\s/.test(l)) { n++; return; }
		if (!/^ldr\w*\s+\w+, \[x(?!29\b)\d+\]/.test(l)) return;
		// 直前2行が置き場所の取り出しなら、これは効果ではない。
		if (/:lo12:\.Lbind_/.test(lines[i - 1] || "")) return;
		n++;
	});
	return n;
}
function effectOnce(note, mk) {
	const one = effectReads(mk(1));
	const many = effectReads(mk(5));
	total++;
	if (one === null || many === null) {
		console.log(`ok   機械 ${note.padEnd(46)} 出せない（名指し済み）`);
		passed++;
		return;
	}
	if (one === many) {
		passed++;
		console.log(`ok   機械 ${note.padEnd(46)} 1回使っても5回使っても ${one} 回`);
	} else {
		console.log(`FAIL 機械 ${note.padEnd(46)} 1回で ${one} 回 / 5回で ${many} 回（使うたびに走っている）`);
	}
}
if (HAS_QEMU || true) {
	const uses = (n) => Array(n).fill("s").join(" + ");
	effectOnce("デフォルト引数の束縛は効果1回", (n) => `f :\n\tp\n\ts : @p\n? ${uses(n)}\nf 0x40100000`);
	effectOnce("トップレベルの束縛も効果1回", (n) => `p : 0x40100000\na : @p\n${uses(n).replace(/s/g, "a")}`);
	// **関数の向こうに隠れた効果も1回。** `ldr` だけ数えていると、命令は `rd` の中に
	// 1本しか無いので通ってしまう——増えるのは `bl` のほうである。
	effectOnce("関数の向こうの効果も1回", (n) => `rd : q ? @q\np : 0x40100000\na : rd p\n${uses(n).replace(/s/g, "a")}`);
	effectOnce("器を通しても効果1回", (n) => `f :\n\tp\n\ts : @p\n? [${Array(n).fill("s").join(" ")}]\nf 0x40100000`);
}

// ---------------------------------------------------------------------------
// 8. 同型の単位律：String と List(Char) は同じ答えを出す
// ---------------------------------------------------------------------------
// `String ≅ List(Char)` は原理8 が「型では無料」と言う同型である。**Char は符号位置**
// なので、どちらの綴りで書いても数え方も引き方も同じでなければならない。
//
// ここは一致（解釈器 対 実機）では守れなかった場所である。`.split("")` と `.length` が
// UTF-16 単位で動いていたため、非 BMP で解釈器が `𐀀𐀁𐀂` を 6 と数え、添字は孤立した
// サロゲートを返していた——**実機の 3 のほうが正しく、オラクルの側が壊れていた**。
// 一致だけを見ていると、こういうものは「両方直すまで」見つからない。
//
// 法則として書けば片側だけで検査できる：**同じ列を2通りに綴って、答えを突き合わせる。**
console.log("\n--- 8. String ≅ List(Char)（符号位置で数える）---");
{
	const S = "`𐀀𐀁𐀂`";                      // 非 BMP（サロゲートペア）
	const L = "[0u10000 0u10001 0u10002]";
	const u = { charset: "utf32" };
	law("長さが一致する（非 BMP）", `||${S}||`, `||${L}||`, u);
	for (const i of [0, 1, 2]) law(`${i} 番目が一致する（非 BMP）`, `${S} ' ${i}`, `${L} ' ${i}`, u);
	law("分解した残りの長さ（非 BMP）", `f : [a ~b] ? ||b||\nf ${S}`, `f : [a ~b] ? ||b||\nf ${L}`, u);
	law("分解した残りの先頭（非 BMP）", `f : [a ~b] ? b ' 0\nf ${S}`, `f : [a ~b] ? b ' 0\nf ${L}`, u);
	// 対照：BMP は元から通っていた。壊していないことを見る。
	law("長さが一致する（BMP）", "||`あいう`||", "||[0u3042 0u3044 0u3046]||", u);
	law("1 番目が一致する（BMP）", "`あいう` ' 1", "[0u3042 0u3044 0u3046] ' 1", u);
}

// ---------------------------------------------------------------------------
// 9. 負の添字は末尾から数える
// ---------------------------------------------------------------------------
// `list_cheat_sheet.md` が「末尾要素の取得 `list ' -1`」と定めている。これは期待値では
// なく**法則**として書ける——`l ' -k` は `l ' (||l|| - k)` と同じものを指す。
//
// 機械の側がこれを見ていなかった。素の添字は符号なしの範囲検査で弾かれて `__` になり、
// **切り出しはもっと悪かった**——`len - (-2)` で長さが増え、`ptr + (-2)×幅` で器の手前を
// 読むので、`__` ではなく**器の外の値がもっともらしく返っていた**。
console.log("\n--- 9. 負の添字は末尾から数える ---");
{
	const L = "l : [10 , 20 , 30]\n";
	const S = "s : `abcde`\n";
	for (const k of [1, 2, 3]) {
		law(`l ' -${k} == l ' (||l|| - ${k})`, `${L}l ' (0 - ${k})`, `${L}l ' ((||l||) - ${k})`);
		law(`s ' -${k} == s ' (||s|| - ${k})`, `${S}s ' (0 - ${k})`, `${S}s ' ((||s||) - ${k})`);
	}
	// 行き過ぎた負は器の外である。均しても負のままなので、範囲外と同じ `__` になる。
	law("行き過ぎた負は範囲外と同じ", `${L}l ' (0 - 4)`, `${L}l ' 99`);
	// **スカラーは1要素の器**なので、末尾も先頭も自分自身である（`[x] ≅ x`）。
	law("7 ' -1 == 7 ' 0", "7 ' (0 - 1)", "7 ' 0");
	law("7 ' -2 は器の外", "7 ' (0 - 2)", "7 ' 9");
	// 切り出しも同じ規則で均す。長さが増えたり手前を読んだりしない。
	law("||l ' -2~|| == ||l ' (||l|| - 2)~||", `${L}||l ' (0 - 2)~||`, `${L}||l ' ((||l||) - 2)~||`);
	law("切り出した先頭も一致", `${L}(l ' (0 - 2)~) ' 0`, `${L}(l ' ((||l||) - 2)~) ' 0`);
	law("String の切り出しも", `${S}||s ' (0 - 2)~||`, `${S}||s ' ((||s||) - 2)~||`);
	// 実行時に決まる添字でも同じ。
	law("実行時の添字でも", `${L}f : i ? l ' i\nf (0 - 1)`, `${L}l ' 2`);
}

// ---------------------------------------------------------------------------
// η：`$` を通っても、読み方は変わらない
// ---------------------------------------------------------------------------
// `ap : f x ? @f x` に `$f` を渡した実体は `<ap$f> : <x> ? <f> <x>` である。これを `f` へ
// 差し替える（η 簡約）のは最適化なので、**呼び出しサイトの読み方を変えてはいけない**——手で
// 書いた同じ射 `h : x ? f x` と同じ値でなければならない。続く字句をいくつ食べるかは、呼ぶ
// 関数の仮引数の並びが宣言している。余る引数を取りたい関数はそう宣言する（`~x` / `[~x]`）。
//
// 一度 η をアリティの多い呼び先へ広げ、`ap $add3 1 2 3` が `add3 1 2 3`（6）になって
// `h 1 2 3`（構築）とずれた。アリティが一致していても、括り・rest・既定値を持つ呼び先は
// 続く字句まで食べる。
console.log("\n--- η：$ を通っても読み方は同じ ---");
{
	// `n` 個の仮引数を素通しする形で比べる。右辺に `ap` を置かない——呼ばれない `ap` は
	// pass4 が「具体化できる呼び出しサイトが無い」と断る。
	const same = (note, f, n, call) => {
		const xs = ["x", "y", "z"].slice(0, n).join(" ");
		law(note, `${f}\nap : g ${xs} ? @g ${xs}\n${call.replace("#", "ap $f")}`, `${f}\nh : ${xs} ? f ${xs}\n${call.replace("#", "h")}`);
	};
	// アリティの多い呼び先（`f : a b c`）は、ここでは比べられない。`h : x ? f x` も `ap$f` も
	// 関数を `$` 無しで返す本体なので、どちらもコンパイル時に名指しされる（compile.test）。
	//
	// **関数を返す関数は、関数オブジェクトの番地で返す**（type_system.md §3.5）。番地で返して
	// `@` で当てたものは、直に当てたのと同じ——返した関数オブジェクトの η である。
	law("@(h 1) 2 3 == f 1 2 3（h : x ? $(f x)）", "f : a b c ? a + b + c\nh : x ? $(f x)\n@(h 1) 2 3", "f : a b c ? a + b + c\nf 1 2 3");
	// アリティも必須の数も同じで、器を丸ごと受けることだけが違う。`f 1 2 3` は器ごと食べる。
	same("器を丸ごと受ける呼び先", "f : [a] ? ||a||", 1, "(# 1 2 3) ' 1");
	same("括りの rest の呼び先", "f : [~s] ? ||s||", 1, "||# 1 2 3||");
	same("rest の呼び先", "f : a ~r ? a + ||r||", 1, "||# 1 2 3||");
	same("既定値の呼び先", "f :\n\ta\n\tb : 10\n? a + b", 1, "||# 1 2||");
	// 括りの rest が2つ目にあっても、食べる数は宣言通り2つ。ここは η してよい形である。
	same("2つ目が括りの rest（η してよい）", "f : x [~s] ? x + ||s||", 2, "||# 1 2 3||");
	// 素の並びどうしなら η してよく、値も直に呼んだのと同じ
	law("app $add 3 4 == add 3 4", "add : a b ? a + b\napp : f x y ? @f x y\napp $add 3 4", "add : a b ? a + b\nadd 3 4");
}

// ---------------------------------------------------------------------------
// `@a b c` は適用：総称の本体が走っても、直に書いたのと同じ
// ---------------------------------------------------------------------------
// `twice : f x ? @f (@f x)` の本体を pass2 が `@f` と `(@f x)` の**合成**と読んでいた（前置 `@` の
// アリティは Infinity なので、括った `(@f x)` がいつまでも未飽和に見えた）。実体にならない道
// （束縛 `p : twice $inc` を経由する）で、解釈器が黙って合成関数を返していた。
console.log("\n--- @a b c は適用（総称の本体） ---");
{
	const F = "inc : n ? n + 1\ndbl : n ? n * 2\n";
	law("p : twice $inc / p 5 == inc (inc 5)", `${F}twice : f x ? @f (@f x)\np : twice $inc\np 5`, `${F}inc (inc 5)`);
	law("q : comp $inc $dbl / q 5 == inc (dbl 5)", `${F}comp : f g x ? @f (@g x)\nq : comp $inc $dbl\nq 5`, `${F}inc (dbl 5)`);
	// 実引数の区切りは pass2 と同じ所で切る。括った形と括らない形は同じ値——前置の印の連なり
	// （`~@p`）や後置の印（`3!`）を割って読むと、別の `$` を実体化して黙って違う答えになった。
	const H = "inc : n ? n + 1\ndbl : n ? n * 2\nh : x g f ? @f x\nv : 10\np : $v\n";
	law("h ~@p $dbl $inc == h (~@p) $dbl $inc", `${H}h ~@p $dbl $inc`, `${H}h (~@p) $dbl $inc`);
	const G = "inc : n ? n + 1\nadd : a b ? a + b\nh : x f g ?\n\tx > 0 : @f x 1\n\t@g x\n";
	law("h 3! $add $inc == h (3!) $add $inc", `${G}h 3! $add $inc`, `${G}h (3!) $add $inc`);
}

// ---------------------------------------------------------------------------
// 撒く＝その場に書く（器に並べた関数は、中身が見えれば呼べる）
// ---------------------------------------------------------------------------
// `proc : [+ 2] , [* 4] , 3` の `proc~` は `[+ 2] [* 4] 3` と書いたのと同じ（operator_table.md の
// 後置 `~` の項）。`'` で取り出した関数はすぐ当てられる。中身が見えない器・値だけの器・積の中で
// 撒く形は、今まで通りスロットを要素として並べる。
console.log("\n--- 撒く＝その場に書く ---");
{
	const P = "proc : [+ 2] , [* 4] , 3\n";
	law("proc~ == [+ 2] [* 4] 3", `${P}proc~`, "[+ 2] [* 4] 3");
	law("(proc ' 0) 5 == [+ 2] 5", `${P}(proc ' 0) 5`, "[+ 2] 5");
	law("字面を撒いても同じ", "[[+ 2], [* 4], 3]~", "[+ 2] [* 4] 3");
	const N = "inc2 : [+ 2]\nmul4 : [* 4]\n";
	law("名前を並べた器", `${N}proc : inc2 , mul4 , 3\nproc~`, `${N}inc2 mul4 3`);
	law("名前を並べた器から取り出す", `${N}proc : inc2 , mul4 , 3\n(proc ' 1) 5`, `${N}mul4 5`);
	// 積の中で撒く形は要素として並べる（cons）——その場に書くのは余積の中だけ
	law("積の中で撒く形は並べる", `${P}||1 , proc~||`, "||1 , [+ 2] , [* 4] , 3||");
	// 裸の関数を入れた器を関数へ渡すのは行を越える（compile.test で名指しを見る）。値だけの器は今まで通り。
	law("値だけの器は今まで通り", "xs : 1 , 2 , 3\n||xs~||", "||1 , 2 , 3||");
	// **器の定義は雛形。** 参照した行で書き直す——別名・括りで書いた器・撒かない参照・実行時の添字
	law("別名の器を撒く", `${P}q : proc\nq~`, "[+ 2] [* 4] 3");
	law("括りで書いた器を撒く", "proc : [[+ 2], [* 4], 3]\nproc~", "[+ 2] [* 4] 3");
	law("撒かない参照は器の字面", `${P}||proc||`, "||[+ 2] , [* 4] , 3||");
	law("実行時の添字で選んで当てる", `${P}f : i ? (proc ' i) 5\nf 1`, "[* 4] 5");
	// 仮引数が器と同じ名前なら、それは仮引数（トップの器ではない）
	law("仮引数が同名なら仮引数を撒く", `${P}f : proc ? ||proc~||\nf (1 , 2)`, "||1 , 2||");
}

// ---------------------------------------------------------------------------
// 絶対値の法則：冪等で、符号を忘れる
// ---------------------------------------------------------------------------
// `|x|` は値を非負の側へ写す射影なので、2回かけても1回と同じであり（冪等）、反転した値からも
// 同じ所へ落ちる（`|0 - x| == |x|`）。どちらも期待値を書かずに言える。**負・0・正**を渡すのは、
// 分岐の無い `cneg` がどの側でも同じ命令で走るので、側ごとに違う壊れ方を命令の数では見分けられない
// からである。`__` は `=` では訊けないので `!` の側で見る（上の「密着演算子は零対象を動かさない」と同じ）。
console.log("\n--- 絶対値：冪等で、符号を忘れる ---");
for (const x of ["-5", "0", "5"]) {
	law(`|(|x|)| == |x|（x = ${x}）`, `f : x ? |(|x|)|\nf ${x}`, `f : x ? |x|\nf ${x}`);
	law(`|0 - x| == |x|（x = ${x}）`, `f : x ? |0 - x|\nf ${x}`, `f : x ? |x|\nf ${x}`);
}
law("!(|__|) == !__（絶対値は零対象を動かさない）", "!(|__|)", "!__");

// ---------------------------------------------------------------------------
// 番地の加減算：負のオフセットは引き算と同じ番地で、溢れる所も同じ
// ---------------------------------------------------------------------------
// 番地の加減算は溢れたら `__` になる（integer_overflow.md §1.1）。機械は右辺の符号で命令が
// 分かれる——番地を引くなら `subs` と `lo` の2命令、負の `Int` を足すなら上の語を運ぶ4命令で、
// **同じ判定が別々の命令列に書いてある**。だから法則で縛る：`p - q` と `p + (0 - q)` は同じ番地を
// 指し、溢れるならどちらも `__` である。溢れの内側と外側の両方の `p` で見るのは、検査を落としても
// 条件コードを取り違えても、内側では両辺が揃ってしまうからである。`q` を小さく取るのは、
// `0 - q` が `Int` として回らない範囲でだけこの等式が成り立つからである。
//
// 溢れない範囲では、足して引けば戻る（`(p + k) - k == p`）。
console.log("\n--- 番地の加減算：負のオフセットと溢れ ---");
for (const p of ["0x10", "0x1000", "0xFFFFFFFFFFFFFFF0"]) {
	for (const q of ["0x8", "0x20"]) {
		law(`p - q == p + (0 - q)（p = ${p}、q = ${q}）`, `f : p q ? p - q\nf ${p} ${q}`, `f : p q ? p + (0 - q)\nf ${p} ${q}`);
	}
}
for (const [p, k] of [["0x1000", "16"], ["0x10", "16"], ["0xFFFFFFFFFFFFFFE0", "16"]]) {
	law(`(p + k) - k == p（p = ${p}、k = ${k}）`, `f : p k ? (p + k) - k\nf ${p} ${k}`, `f : p k ? p\nf ${p} ${k}`);
	law(`(p - k) + k == p（p = ${p}、k = ${k}）`, `f : p k ? (p - k) + k\nf ${p} ${k}`, `f : p k ? p\nf ${p} ${k}`);
}

