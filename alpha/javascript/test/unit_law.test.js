/**
 * **単位律で検査する。期待値は書かない。**
 *
 * これまでの検査は「インタプリタと実機が一致するか」で見ていた（`qemu.test.js`）。
 * それは強い軸だが、**両方が同じように間違っていると通ってしまう**——実際、UTF-32 の
 * 文字数は解釈器の側が壊れていて（JS の UTF-16 サロゲートが漏れる）、実機のほうが
 * 正しかった。オラクルが壊れているとき、一致は何も保証しない。
 *
 * ここは別の軸を足す。**片側だけで確かめられる法則**、すなわち単位律である。
 *
 *   どの演算 op についても   a op 単位元 == a
 *   どの分解についても       ||残り|| >= 0
 *   どの束縛についても       効果は1回
 *   どの仮引数の形でも       f __ == __     （完全性公理＝ε）
 *
 * 期待値（`7 + __ は 7`）を書くのではなく、**法則（`a + __ は a`）**を書く。だから
 * 解釈器と実機のそれぞれについて独立に成否が出るし、両方が同じ間違いをしても通らない。
 *
 * **なぜ単位律なのか。** `__` は双代数の単位元として振舞うことを要請されている
 * （`unit.md`）。単位元は演算の不動点であり、**演算を演算たらしめているものが単位律**
 * である。そして単位元の「側」が演算の役を決めている：
 *
 *   両側に単位元がある   `+ - * / % ^ << >> ; ,`   作る
 *   左だけ               `&`（単位元は `!__`）      選ぶ
 *   左だけ               `|`（単位元は `__`）       落とす
 *   右だけ               `'`（単位元は `0`）        観測する
 *   無い（`__` は零元）  `< =`                      判定する
 *
 * 同じ `+` でも、**結果が番地なら `__` は両側で零元**である（節1b）。役を決めているのは演算子
 * だけではなく、結果の型でもある——溢れた番地を単位元として通すと、次の演算で生き返る。
 *
 * 実際、この軸で見つかった不具合は「別々の4件」ではなく **1つの規準の4箇所**だった。
 *
 * 実行: node test/unit_law.test.js
 */
import peggy from "peggy";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { compile } from "../compile.js";
import { generateAsm } from "../pass4.js";
import { evaluate, newRuntimeEnv, UNIT, observe, isUnit } from "../interpreter.js";
import { runAsm, asInt, available, toolReport } from "../qemu_run.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const parser = peggy.generate(fs.readFileSync(path.join(__dirname, "..", "sign.pegjs"), "utf8"));

let passed = 0;
let total = 0;

const HAS_QEMU = available();
if (!HAS_QEMU) console.log(`実機側は飛ばす（${toolReport()}）——解釈器側の法則だけ見る`);

/** 解釈器で走らせて、見える姿の文字列を返す。`qemu.test.js` の `interp` と同じ揃え方。 */
function interp(source, charset = "ascii") {
	const { nodes } = compile(source, { parse: parser.parse, charset });
	const env = newRuntimeEnv(null, charset);
	let r = UNIT;
	for (const node of nodes) r = evaluate(node, env);
	if (isUnit(r)) return "__";
	const o = observe(r);
	if (o === undefined || o === null) return "__";
	if (typeof o === "string" && [...o].length === 1) return String(o.codePointAt(0));
	if (o && typeof o === "object" && o.__identity__) return "0";
	return String(o);
}

/** 機械で走らせる。出せないものは `拒否` を返す——**出せないことと間違うことは別**である。 */
function machine(source, charset = "ascii", layer = 1) {
	const { nodes, env } = compile(source, { charset });
	const r = generateAsm(nodes, env, { target: "aarch64_qemu", charset, layer });
	if (r.diagnostics.length) return "拒否";
	const v = asInt(runAsm(r.text)[0]);
	return v === null ? "__" : String(v);
}

/**
 * **法則をひとつ検査する。** 左辺の式と右辺の式が同じ値になることだけを見る。
 * 期待値は書かない——`law("a + __ == a", "7 + __", "7")` ではなく、両方を走らせて
 * 突き合わせる。解釈器と実機は**別々に**判定する（片方が拒否ならその側は数えない）。
 */
// 側ごとの「試した数」と「拒否で飛ばした数」。**覆いの広さそのものを golden にする。**
const attempted = {};
const skipped = {};

function law(note, lhs, rhs, opts = {}) {
	const { charset = "ascii", wrap = (e) => e } = opts;
	const sides = [["解釈", (s) => interp(wrap(s), charset)]];
	if (HAS_QEMU) sides.push(["機械", (s) => machine(wrap(s), charset)]);
	for (const [who, run] of sides) {
		let a, b;
		try { a = run(lhs); } catch (e) { a = "例外：" + e.message; }
		try { b = run(rhs); } catch (e) { b = "例外：" + e.message; }
		// **出せないことと間違うことは別である。** 片方でも「拒否」なら、その側は法則に
		// ついて何も言っていない（「まだ」と言えている）ので数えない。ここを失敗に数えると、
		// 実装の穴と設計の誤りが混ざって、直したいものが見えなくなる。
		//
		// **ただし数えないことと見ないことは別である。** ここを素通しにしていたので、
		// `pass4` が広い範囲で出せなくなっても**この門は緑のまま**だった——実測で、機械側を
		// 全部「拒否」にしても 252/252 で通る。点数は「法則が成り立った回数」と「まだと
		// 言えている回数」を区別しないので、覆いが痩せたことが数字に出ない。
		// 側ごとに**試した数と飛ばした数**を控え、下で golden に突き合わせる。
		attempted[who] = (attempted[who] || 0) + 1;
		if (a === "拒否" || b === "拒否") {
			skipped[who] = (skipped[who] || 0) + 1;
			continue;
		}
		total++;
		if (a === b) {
			passed++;
			console.log(`ok   ${who} ${note.padEnd(46)} ${a}`);
		} else {
			console.log(`FAIL ${who} ${note.padEnd(46)} ${lhs} → ${a} / ${rhs} → ${b}`);
		}
	}
}

// ---------------------------------------------------------------------------
// 1. 両側単位元：作る演算は `__` を不動点に持つ
// ---------------------------------------------------------------------------
// `a op __ == a` と `__ op a == a` の両方。**引き算や除算で向きが答えを変えない**のは
// 一見おかしいが、これは爆発律の代償として意図的にそうなっている（`operator_table.md`）
// ——単位元がひとつしかない以上、どの演算もそれを不動点にするしかない。
console.log("--- 1. 両側単位元（作る演算）---");
for (const op of ["+", "-", "*", "/", "%", "^", "<<", ">>", ";", ","]) {
	law(`a ${op} __ == a`, `7 ${op} __`, "7");
	law(`__ ${op} a == a`, `__ ${op} 7`, "7");
}

// ---------------------------------------------------------------------------
// 1b. 結果が番地なら、`__` は両側で零元である
// ---------------------------------------------------------------------------
// 結果の型が `Address` なら `a op __ == __` と `__ op a == __`（operator_table.md の爆発律の欄の
// 例外）。溢れて `__` になった番地を単位元として通すと、次の演算で番地が生き返る——任意の記憶を
// 指すので致命的である。足す数の側が失われたときに `a` を返すのも、意図と違う番地を黙って出す
// ので同じく致命的で、だから左右を問わない。
//
// **結果の型は昇格格子が決める。** 番地を左に置いても（`Address ⊕ Unit`）、`__` を左に置いても
// （`Unit ⊕ Address`）結果は `Address` である。`Int` を置けば `Int` なので節1の単位律に戻る
// ——同じ `__` が型によって単位元にも零元にもなることを、同じ入力の形で並べて見る。
// `*` と `^` は番地の域に射が無いので、`__` の有無によらず `__` である（下の「番地の積は __」）。
console.log("\n--- 1b. 結果が番地なら __ は両側で零元 ---");
for (const op of ["+", "-", "*", "/", "%", "^"]) {
	law(`p ${op} __ == __（番地）`, `f : p ? p ${op} __\nf 0x1000`, "__");
	law(`__ ${op} p == __（番地）`, `f : p ? __ ${op} p\nf 0x1000`, "__");
	law(`n ${op} __ == n（Int は単位元のまま）`, `f : n ? n ${op} __\nf 7`, "f : n ? n\nf 7");
	law(`__ ${op} n == n（Int は単位元のまま）`, `f : n ? __ ${op} n\nf 7`, "f : n ? n\nf 7");
}
// ビット演算も同じ族だが、見るのは番地を左に置いた形だけである。`__ << p` は pass3 がまだ
// `Unit ⊕ T → T` を当てず型が `Unit` のままなので、番地と分からない（interpreter.js の `evalBit`）。
for (const op of ["<<", ">>"]) {
	law(`p ${op} __ == __（番地）`, `f : p ? p ${op} __\nf 0x1000`, "__");
	law(`n ${op} __ == n（Int は単位元のまま）`, `f : n ? n ${op} __\nf 7`, "f : n ? n\nf 7");
}
// **実行時に `__` になる辺でも同じ。** 字面の `__` だけを見ていると、`__` になり得る辺を探す道
// （pass4 の `cannotBeUnit`）が壊れても通ってしまう。下の3つは実測で番地を返していた形である。
law("溢れた番地から引いても __", "f : p n m ? (p + n) - m\nf 0xFFFFFFFFFFFFFFF0 32 32", "__");
law("溢れた番地に負の数を足しても __", "f : p n m ? p + n + m\nf 0xFFFFFFFFFFFFFFF0 32 -4", "__");
law("niche に落ちた Int をオフセットにしても __", "f : p a b ? p - (a + b)\nf 0x1000 9223372036854775807 1", "__");
law("範囲の外のオフセットは __", "f : p i ? p + ([1 2] ' i)\nf 0x1000 5", "__");
law("Int の範囲の外は単位元のまま", "f : n i ? n + ([1 2] ' i)\nf 7 5", "f : n ? n\nf 7");
// **論理は変わらない。** `__` は偽なので、`|` の左単位律（節2）がそのまま溢れた番地にも効く。
law("溢れた番地 | q == q", "f : p n q ? (p + n) | q\nf 0xFFFFFFFFFFFFFFF0 32 8192", "f : q ? q\nf 8192");
law("溢れない番地 | q == 番地", "f : p n q ? (p + n) | q\nf 0x1000 32 8192", "f : p n ? p + n\nf 0x1000 32");
// **再帰を通っても番地は番地である。** 自己呼び出しが渡す `p + 8` の型は p の型から作られるので、
// それを「p は何で呼ばれたか」の証拠に数えると、本体の字面 `8` から来た `Int` が自分を支える
// （pass3 の `intPartnerDeferred`）。下の5つは実測で、どれも両エンジンが揃って番地を回していた
// ——一致だけを見る検査では見えない形である。
const tail = (step, start, n) => `f : p n ?\n\tn = 0 : p\n\tf (${step}) (n - 1)\nf ${start} ${n}`;
law("自己末尾再帰：上へ溢れた番地は __", tail("p + 8", "0xFFFFFFFFFFFFFFE0", 4), "__");
law("自己末尾再帰：0 の下へ出た番地は __", tail("p - 8", "0x10", 3), "__");
law("自己末尾再帰：溢れなければ番地を返す", tail("p + 8", "0x1000", 4), "0x1020");
law("相互再帰：足すのが相手の側でも __", "f : p n ?\n\tn = 0 : p\n\tg p (n - 1)\ng : p n ? f (p + 8) n\nf 0xFFFFFFFFFFFFFFE0 4", "__");
law("自己末尾再帰：字面との比較が居ても __", "f : p n ?\n\tp = 0 : 0\n\tn = 0 : p\n\tf (p + 8) (n - 1)\nf 0xFFFFFFFFFFFFFFE0 4", "__");
// **境目の外側。** 字面を左に置けば和は `Int`（§3.2 の左辺優先）なので、再帰の中で回るのが正しい
// ——番地と `Int` の間に強弱を作って直すと、ここが `__` に変わる。
law("字面が左の和は Int なので回る", tail("8 + p", "0xFFFFFFFFFFFFFFE0", 4), "0");
law("Int の自己末尾再帰は回る", "f : a n ?\n\tn = 0 : a\n\tf (a + 2) (n - 1)\nf 9223372036854775807 1", "-9223372036854775807");
// **番地の域に、掛け算・冪・階乗の射は無い**（利用者の決定 2026-09-14、layout.js の `addressWithoutArrow`）。
// 射が無いので零射を通る——溢れない積でも `__` である。以前は溢れを見て番地を返していた（`0x1000 * 3` が
// `0x3000`）。左辺が数なら `Int` の域なので（左辺優先）、ふつうに掛ける。
law("番地の積は __（溢れなくても）", "f : p n ? p * n\nf 0x1000 3", "__");
law("番地どうしの積は __", "f : p q ? p * q\nf 0x10 0x20", "__");
law("0 番地の積も __", "f : p n ? p * n\nf 0x0 -4", "__");
law("番地の冪は __", "f : p k ? p ^ k\nf 0x10 2", "__");
law("番地の階乗は __", "f : p ? p!\nf 0x5", "__");
law("__ を左に置いても番地の積は __", "f : p ? __ * p\nf 0x10", "__");
law("左辺が数なら Int の積", "f : n p ? n * p\nf 3 0x1000", "f : n m ? n * m\nf 3 4096");
// レビューで見つかった形（2026-09-14）。射の無い積の `__` を外の `Int` の算術が数として足していた（機械だけ）、
// 番地の字面を掛けた仮引数が番地に型付けされて数で呼んでも `__` だった、規則の歩幅が `__` でも機械が番地を返した。
// **射が無くても域は保つ**（利用者の裁定 2026-09-21）。ここはかつて「外の `Int` の算術で
// 単位元」＝ **1** を法則として書いていた。値としては正しく、両エンジンも一致していたが、
// **番地から数が生まれる**——利用者：「アドレス型の場合の想定なら、1ではあるけどね…
// **これで読み書きされるとたまったものじゃない**」。
//
// `p * 2` が `Unit` へ落ちると `Unit + Int` が `Int` へ昇格し、`__` が**単位元の側**で
// 読まれていた。域を保てば `Address + Int` は `Address` なので吸収する。
//
// **`__` は `0` と同じ振る舞いをする。** `+ 0` では単位元、`× 0` では吸収元——同じ値が
// 演算によって役を変える（環の構造）。番地の `__` は「**その番地は存在しない**」という
// 一階述語が偽であることで、**偽の存在主張はその上に建つ全部を吸収する**。だから番地の
// 域では吸収元の側に立つ。
law("射の無い積は外の算術でも __（域を保つ）", "f : p ? (p * 2) + 1\nf 0x10", "__");
law("射の無い冪も外で __", "f : p ? (p ^ 2) + 1\nf 0x10", "__");
law("2段外でも __ のまま", "f : p ? ((p * 2) + 1) - 3\nf 0x10", "__");
// **対照。射が在る演算は落ちない**——ここが赤いと上は「番地は何をしても `__`」を見ているだけになる。
law("対照：ずらす（射が在る）", "f : p ? (p + 0) + 1\nf 0x10", "17");
law("対照：数の算術は単位元のまま", "f : n ? (n * 2) + 1\nf 7", "15");
law("番地の字面を掛けても仮引数は番地にならない", "f : k ? k * 0x10\nf 3", "48");
law("歩幅が射の無い積の規則は __", "f : p q i ? [p ~+ (q * 2)] ' i\nf 0x1000 0x8 1", "__");
law("歩幅が __ の規則を切っても __", "f : p q i ? ([p ~+ (q * 2)] ' i~) ' 0\nf 0x1000 0x8 1", "__");
law("番地を起点にした等比の規則は __", "f : p i ? [p ~* 2] ' i\nf 0x10 1", "__");
law("番地を起点にした割る規則は値を持つ", "f : p i ? [p ~/ 2] ' i\nf 0x100 1", "f : n ? n\nf 0x80");
// **番地の左シフトは `p * 2^k` なので射が無い。右シフトは `p / 2^k`（枠の番号）**（利用者の決定 2026-09-15）。
law("番地の左シフトは __", "f : p ? p << 4\nf 0x10", "__");
law("番地の右シフトは枠の番号", "f : p ? p >> 4\nf 0x100", "f : p ? p / 16\nf 0x100");
// **番地と数は数学の値で比べる——番地は負の数より常に大きい**（利用者の決定 2026-09-15）。以前の機械は上半分の
// 番地を負の数と読み、`0xFFFF800000000000 > -1` を偽、`0xFFFFFFFFFFFFFFFF = -1` を真と答えていた。
law("上半分の番地 > 負の数は真", "f : p n ? p > n\nf 0xFFFF800000000000 -1", "f : p ? p\nf 0xFFFF800000000000");
law("上半分の番地 < 負の数は __", "f : p n ? p < n\nf 0xFFFF800000000000 -1", "__");
law("ビットが同じでも番地 = 負の数は __", "f : p n ? p = n\nf 0xFFFFFFFFFFFFFFFF -1", "__");
law("負の数 < 上半分の番地は真", "f : n p ? n < p\nf -1 0xFFFF800000000000", "-1");
law("上半分の番地 > 正の数は真", "f : p ? p > 16\nf 0xFFFF800000000000", "f : p ? p\nf 0xFFFF800000000000");
// **番地の域では、0 以下の数で割ると `__`**（利用者の決定 2026-09-14）。0 で割った剰余が被除数のままだと、
// 揃えの形 `p - (p % a)` が黙って 0 番地を出す。以前は負の数で割っても被除数が小さければ商 0（番地 0）だった。
law("番地の商：負の数で割ったら __", "f : p n ? p / n\nf 0x1000 -4", "__");
law("番地の商：端数が出ても __", "f : p n ? p / n\nf 0x1003 -4", "__");
law("番地の商：被除数が小さくても負の数で割れば __", "f : p n ? p / n\nf 0x3 -4", "__");
law("番地の商：正の数で割れば枠の番号", "f : p n ? p / n\nf 0x3000 4096", "f : n ? n\nf 0x3");
law("番地の剰余：0 で割ったら __", "f : p n ? p % n\nf 0x1003 0", "__");
law("番地の剰余：負の数で割ったら __", "f : p n ? p % n\nf 0x1003 -4", "__");
law("揃え：p - (p % a) は a で割り切れる番地", "f : p a ? p - (p % a)\nf 0x1234 4096", "f : p ? p\nf 0x1000");
law("揃え：a が 0 なら 0 番地ではなく __", "f : p a ? p - (p % a)\nf 0x1234 0", "__");
law("切り上げの揃えも a が 0 なら __", "f : p a ? (p + (a - 1)) - ((p + (a - 1)) % a)\nf 0x1234 0", "__");
// **マスクも番地のまま**（左辺優先、§3.6）。語は符号なしで見る——以前の解釈器は `Int` として回し、上半分の
// 番地をマスクすると負の数になって、次の番地の算術で `__` へ落ちていた。機械はまだビット演算を出さない。
law("剰余で揃えてもマスクで揃えても同じ番地", "f : p ? p - (p % 4096)\nf 0xFFFF800000001234", "f : p ? p && !!0xFFF\nf 0xFFFF800000001234");
